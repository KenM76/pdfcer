//! # `pdfcer extract-text` integration tests
//!
//! Black-box tests over the **real binary**, asserting the process
//! contract a script depends on and a refactor cannot see: the exit
//! code, which stream carries which payload, the stable `key=value`
//! result line, and the shape of `--json`.
//!
//! Unlike the sibling `render_page.rs`, these use the **committed
//! fixtures** in `fixtures/synthetic/text/` rather than building PDFs
//! inline. That is deliberate: those fixtures already exist for the
//! `pdfcer-core` integration tests, each one is a worked example from a
//! specific ISO 32000-1 clause (see the directory's `PROVENANCE.md`),
//! and duplicating them here would create two sources of truth for what
//! "the `/ActualText` fixture" means. `docs/LEGAL.md` §5 is satisfied
//! the same way either route — every byte is synthetic, generated by
//! `tools/gen-text-fixtures.py`.
//!
//! ## The channel-routing contract, restated
//!
//! `extract-text` has two things to say and must never mix them:
//!
//! | invocation | stdout | stderr |
//! |---|---|---|
//! | plain, no `-o` | the text | the result line + notes |
//! | plain, `-o FILE` | the result line | the notes |
//! | `--json`, no `-o` | the JSON | the result line + notes |
//! | `--json`, `-o FILE` | the result line | the notes |
//!
//! A pipeline (`extract-text f.pdf | grep …`) therefore gets clean text
//! and still shows the honesty line on the terminal.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

/// Path to the freshly built binary — Cargo sets this for integration
/// tests, so the test always exercises the binary from the same build.
const BIN: &str = env!("CARGO_BIN_EXE_pdfcer");

/// A committed fixture path.
fn fixture(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../fixtures/synthetic/text")
        .join(name)
}

/// Run `extract-text` with the given extra arguments.
fn run(name: &str, args: &[&str]) -> Output {
    let mut cmd = Command::new(BIN);
    cmd.arg("extract-text").arg(fixture(name));
    for arg in args {
        cmd.arg(arg);
    }
    cmd.output().expect("the binary runs")
}

fn stdout(out: &Output) -> String {
    String::from_utf8_lossy(&out.stdout).into_owned()
}

fn stderr(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

/// Parse the stable result line's `key=value` pairs from a stream.
fn result_line(text: &str) -> std::collections::HashMap<String, String> {
    let line = text
        .lines()
        .find(|l| l.starts_with("extracted "))
        .unwrap_or_else(|| panic!("no result line in:\n{text}"));
    line.split_whitespace()
        .filter_map(|token| token.split_once('='))
        .map(|(k, v)| (k.to_string(), v.to_string()))
        .collect()
}

