#[test]
fn a_missing_file_maps_to_the_io_exit_code() {
    let out = Command::new(BIN)
        .arg("extract-text")
        .arg("no-such-file-anywhere.pdf")
        .output()
        .expect("runs");
    assert_eq!(out.status.code(), Some(3));
}

#[test]
fn a_non_pdf_maps_to_the_not_a_pdf_exit_code() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../fixtures/synthetic/not-a-pdf.bin");
    let out = Command::new(BIN)
        .arg("extract-text")
        .arg(&path)
        .output()
        .expect("runs");
    assert_eq!(out.status.code(), Some(4));
}
