#[test]
fn artifacts_are_excluded_by_default_and_included_on_request() {
    let without = stdout(&run("artifact-and-reversed.pdf", &[]));
    assert!(!without.contains("Running head"));
    assert!(without.contains("Real content"));

    let with = stdout(&run("artifact-and-reversed.pdf", &["--include-artifacts"]));
    assert!(with.contains("Running head"));
}

#[test]
fn a_page_selection_is_honoured_and_a_bad_one_is_refused_by_name() {
    let ok = run("simple-winansi.pdf", &["--pages", "1"]);
    assert_eq!(ok.status.code(), Some(0));

    // Exit 9 is EDIT_REFUSED: the document was readable and pdfcer
    // declined the request as asked — distinct from "broken file".
    let bad = run("simple-winansi.pdf", &["--pages", "1-9"]);
    assert_eq!(bad.status.code(), Some(9));
    assert!(stderr(&bad).contains("--pages"));
}

