#[test]
fn the_result_line_reports_the_ladder_rung_by_rung() {
    let out = run("simple-winansi.pdf", &[]);
    let kv = result_line(&stderr(&out));
    assert_eq!(kv["codes"], "21");
    assert_eq!(kv["via_encoding"], "21");
    assert_eq!(kv["via_tounicode"], "0");
    assert_eq!(kv["failed"], "0");
    assert_eq!(kv["sourced_pct"], "100.0");
    // The derived half is reported separately, and is non-zero here.
    assert_eq!(kv["spaces_derived"], "1");
    assert_eq!(kv["lines_derived"], "1");
}

#[test]
fn the_identity_h_dead_end_is_visible_in_the_result_line() {
    let out = run("identity-h-no-tounicode.pdf", &[]);
    let err = stderr(&out);
    let kv = result_line(&err);
    assert_eq!(kv["failed"], kv["codes"], "every code must fail");
    assert_eq!(kv["sourced_pct"], "0.0");
    assert_eq!(kv["identity_no_tounicode"], "1");
    assert!(
        err.contains("no Unicode is recoverable"),
        "the named diagnostic must reach the operator: {err}"
    );
}

#[test]
fn to_unicode_resolution_is_reported_as_rung_one() {
    let out = run("identity-h-tounicode.pdf", &[]);
    let kv = result_line(&stderr(&out));
    assert_eq!(kv["via_encoding"], "0", "a composite font has no rung 2");
    assert!(kv["via_tounicode"].parse::<u64>().unwrap() > 0);
    assert_eq!(kv["failed"], "1", "the deliberately uncovered code");
}

#[test]
fn document_level_facts_appear_in_the_result_line() {
    let out = run("tagged-marked.pdf", &[]);
    let kv = result_line(&stderr(&out));
    assert_eq!(kv["tagged"], "true");
    assert_eq!(kv["suspects"], "true");
    assert_eq!(kv["struct_tree"], "true");
}

