#[test]
fn text_goes_to_stdout_and_the_result_line_to_stderr() {
    let out = run("simple-winansi.pdf", &[]);
    assert_eq!(out.status.code(), Some(0));
    let text = stdout(&out);
    assert!(text.starts_with("Hello world"), "stdout: {text:?}");
    assert!(
        !text.contains("extracted "),
        "the result line must not pollute piped text"
    );
    assert!(stderr(&out).contains("extracted "));
}

#[test]
fn with_an_output_file_the_result_line_takes_stdout() {
    // Per-call-unique temp dir: `process::id()` is binary-safe and the
    // process-global atomic counter is thread-safe, so no two concurrent tests
    // can collide on this scratch dir (fully-qualified `atomic` types keep the
    // guard self-contained without adding a `use`).
    let dir = {
        static N: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(0);
        let n = N.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        std::env::temp_dir().join(format!("pdfcer-extract-{}-{n}", std::process::id()))
    };
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("out.txt");
    let out = run("simple-winansi.pdf", &["--output", path.to_str().unwrap()]);
    assert_eq!(out.status.code(), Some(0));
    assert!(stdout(&out).starts_with("extracted "));
    let written = std::fs::read_to_string(&path).unwrap();
    assert!(written.starts_with("Hello world"));
    assert!(written.ends_with('\n'), "a text file ends with a newline");
    let _ = std::fs::remove_dir_all(&dir);
}

