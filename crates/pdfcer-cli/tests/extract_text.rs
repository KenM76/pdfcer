#[test]
fn json_exposes_the_sourced_derived_split_run_by_run() {
    let out = run("simple-winansi.pdf", &["--json"]);
    assert_eq!(out.status.code(), Some(0));
    let json = stdout(&out);

    // The derived space is present, flagged as NOT sourced.
    assert!(json.contains("\"origin\": \"derived_word_space\""));
    assert!(json.contains("\"origin\": \"derived_line_break\""));
    assert!(json.contains("\"origin\": \"glyphs\""));
    assert!(json.contains("\"sourced\": false"));
    assert!(json.contains("\"sourced\": true"));

    // Per-glyph ladder provenance.
    assert!(json.contains("\"rung\": \"encoding_agl\""));
    // Counters and the document-level facts.
    assert!(json.contains("\"codes_total\": 21"));
    assert!(json.contains("\"tagged\": false"));
    assert!(json.contains("\"sourced_fraction\": 1.000000"));
}

#[test]
fn json_output_is_syntactically_well_formed() {
    // No JSON parser in the dependency graph, so this checks the two
    // properties a hand-rolled emitter actually gets wrong: unbalanced
    // brackets, and unescaped control characters or quotes inside string
    // literals. The fixture set deliberately includes a derived line
    // break (a literal `\n` inside a run's text), which is exactly the
    // case a naive emitter breaks on.
    for name in [
        "simple-winansi.pdf",
        "identity-h-tounicode.pdf",
        "identity-h-no-tounicode.pdf",
        "actual-text-drucker.pdf",
        "artifact-and-reversed.pdf",
        "tagged-marked.pdf",
    ] {
        let json = stdout(&run(name, &["--json"]));
        assert!(json.starts_with('{'), "{name}");
        assert!(json.trim_end().ends_with('}'), "{name}");

        let mut depth = 0i32;
        let mut in_string = false;
        let mut escaped = false;
        for ch in json.chars() {
            if in_string {
                if escaped {
                    escaped = false;
                } else if ch == '\\' {
                    escaped = true;
                } else if ch == '"' {
                    in_string = false;
                } else {
                    assert!(
                        (ch as u32) >= 0x20,
                        "{name}: raw control character inside a JSON string"
                    );
                }
                continue;
            }
            match ch {
                '"' => in_string = true,
                '{' | '[' => depth += 1,
                '}' | ']' => depth -= 1,
                _ => {}
            }
            assert!(depth >= 0, "{name}: unbalanced brackets");
        }
        assert_eq!(depth, 0, "{name}: unbalanced brackets");
        assert!(!in_string, "{name}: unterminated string");
    }
}

#[test]
fn json_marks_an_actual_text_run_atomic() {
    // §14.9.4 N4: no per-character correspondence exists across a
    // replacement, so the JSON must carry no `glyphs` array for it —
    // and must still mark the run sourced, because the VALUE is.
    let json = stdout(&run("actual-text-drucker.pdf", &["--json"]));
    let run_json = json
        .lines()
        .find(|l| l.contains("\"origin\": \"actual_text\""))
        .expect("the replacement run is present");
    assert!(run_json.contains("\"sourced\": true"));
    assert!(!run_json.contains("\"glyphs\""));
    assert!(
        run_json.contains("\"bbox\""),
        "the covered region is all it has"
    );
}

