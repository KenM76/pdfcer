//! `docs/cross-cutting.md` is generated from [`expect`]; this test fails when
//! the file on disk is stale. `PDFCER_BLESS=1` rewrites it.

use std::fmt::Write as _;

use crate::xcut::{ObjectKind, OpGroup, expect};

const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/cross-cutting.md");

fn render() -> String {
    let mut out = String::from(
        "# Cross-cutting coverage matrix\n\n\
         GENERATED by `cargo test -p pdfcer-core xcut` from `pdfcer_core::xcut::expect`\n\
         (decision 228). Do not edit; run with `PDFCER_BLESS=1` to regenerate.\n\n\
         Rows are `ObjectKind::id()`, columns `Op::id()`. Cells: `ok[:changes]`,\n\
         `remove`, `consume`, `represent`, `refused:<cause>`, `n/a:\"<reason>\"` or\n\
         `pass:<id>` (not yet driven; the Pass that will drive it).\n",
    );
    for group in OpGroup::ALL {
        let ops = group.ops();
        let _ = write!(out, "\n## {}\n\n| kind |", group.id());
        for op in ops {
            let _ = write!(out, " {} |", op.id());
        }
        out.push_str("\n|---|");
        out.push_str(&"---|".repeat(ops.len()));
        out.push('\n');
        for &kind in ObjectKind::ALL {
            let _ = write!(out, "| {} |", kind.id());
            for &op in ops {
                let _ = write!(out, " {} |", expect(op, kind));
            }
            out.push('\n');
        }
    }
    out
}

#[test]
#[allow(clippy::unwrap_used)]
fn the_matrix_doc_is_current() {
    let fresh = render();
    if std::env::var_os("PDFCER_BLESS").is_some() {
        std::fs::write(PATH, &fresh).unwrap();
        return;
    }
    let on_disk = std::fs::read_to_string(PATH)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        on_disk == fresh,
        "docs/cross-cutting.md is stale; rerun with PDFCER_BLESS=1"
    );
}
