//! Certificate-chain trust evaluation: does a signer's certificate chain, by
//! valid signatures, to a trusted anchor? (`Pass 10.3`, decision 133.)
//!
//! # What this answers, and what it deliberately does NOT
//!
//! Given a signer's certificate, the intermediate certificates embedded in the
//! signature, and a pool of trusted anchors (e.g. [`crate::trust_store`]'s
//! AATL/EUTL set read from an installed Acrobat), this walks issuer→subject
//! links, **verifying each link's signature** with the issuer's public key,
//! until it either reaches a trusted anchor ([`ChainVerdict::Trusted`]) or runs
//! out of chain ([`ChainVerdict::Untrusted`]).
//!
//! It is a **cryptographic-linkage** check PLUS the deterministic, no-network
//! parts of RFC 5280 path validation (`Pass 10.5`):
//!
//! - **Signature linkage** — every issuer→subject link's signature verifies
//!   with the issuer's key (`Pass 10.3`).
//! - **Validity dates** — when the caller supplies a reference clock `now`
//!   (the signing time), every certificate in the chain must satisfy
//!   `notBefore ≤ now ≤ notAfter` (RFC 5280 §4.1.2.5). If no clock is given,
//!   this check is skipped and [`PathChecks::validity_checked`] is `false`.
//! - **CA / key-usage constraints** — any certificate used as an
//!   *intermediate* issuer must assert `basicConstraints` `cA` TRUE
//!   (§4.2.1.9) and must not have a `keyUsage` that clears `keyCertSign`
//!   (§4.2.1.3). A configured trust anchor is trusted as the operator
//!   declared it, so its own `cA` bit is not re-litigated — but its validity
//!   dates still are.
//!
//! It does **not** check **revocation** (CRL/OCSP). That is inherently a
//! network act, and `pdfcer-core` never touches the network (the `no-network`
//! CI gate) — so revocation belongs to a shell (which fetches) validating a
//! response, or to embedded DSS/LTV data, and is a named later increment.
//! [`PathChecks::revocation_checked`] is therefore always `false` this build.
//! The caller MUST disclose, from [`PathChecks`], exactly which checks ran, so
//! a `Trusted` verdict is never read as more than it verified. The failure
//! direction stays safe: every uncertainty resolves to
//! [`ChainVerdict::Untrusted`], never to a false `Trusted`.
//!
//! # Security posture
//!
//! - **Conservative by construction.** An unparseable cert, an unsupported
//!   signature algorithm (RSA PKCS#1 v1.5, RSASSA-PSS and ECDSA are supported;
//!   anything else is declined, which is the safe direction), a missing issuer,
//!   a bad signature, a non-CA intermediate, a certificate outside its validity
//!   window, or a cycle all yield `Untrusted`/`SignerUnparseable`. Nothing that
//!   fails to verify is ever reported trusted.
//! - **Bounded.** The walk is depth-capped and cycle-guarded (by subject DN),
//!   so a hostile chain cannot loop or run long.

