    /// Build a `TrustAnchorSet` holding one anchor cert (DER) tagged AATL.
    fn anchor_set(der: Vec<u8>) -> TrustAnchorSet {
        let cert = cms::parse_certificate(&der).expect("anchor parses");
        TrustAnchorSet {
            anchors: vec![TrustAnchor {
                subject: cert.subject.clone(),
                issuer: cert.issuer.clone(),
                serial_hex: String::new(),
                not_before: None,
                not_after: None,
                sources: vec!["AATL".to_owned()],
                trust_bits: 32,
                policy_oids: vec![],
                der,
                id: None,
            }],
            undecodable: 0,
        }
    }

    #[test]
    fn a_leaf_that_chains_to_a_trusted_root_is_trusted() {
        // root_der signs leaf_der; root is the anchor.
        let (root_der, leaf_der) = root_and_leaf();
        let anchors = anchor_set(root_der);
        match evaluate(&leaf_der, &[], &anchors, None) {
            ChainVerdict::Trusted { source, .. } => assert_eq!(source, vec!["AATL".to_owned()]),
            other => panic!("expected Trusted, got {other:?}"),
        }
    }

    #[test]
    fn a_leaf_with_no_matching_anchor_is_untrusted_not_unknown() {
        let (_root_der, leaf_der) = root_and_leaf();
        // An empty trust store: the signer parses but chains to nothing trusted.
        let empty = TrustAnchorSet::default();
        assert_eq!(empty.counts(), SourceCounts::default());
        match evaluate(&leaf_der, &[], &empty, None) {
            ChainVerdict::Untrusted { .. } => {}
            other => panic!("expected Untrusted, got {other:?}"),
        }
    }

    #[test]
    fn garbage_is_signer_unparseable() {
        let anchors = TrustAnchorSet::default();
        assert_eq!(
            evaluate(b"not a certificate", &[], &anchors, None),
            ChainVerdict::SignerUnparseable
        );
    }

