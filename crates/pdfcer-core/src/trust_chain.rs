    #[test]
    fn a_valid_three_cert_chain_with_a_ca_intermediate_is_trusted() {
        // leaf <- good CA (basicConstraints CA:TRUE) <- root (anchor). A clock
        // inside every certificate's validity window is supplied (Pass 10.5).
        let anchors = anchor_set(P105_ROOT_DER.to_vec());
        match evaluate(
            P105_LEAF_VIA_GOOD_DER,
            &[P105_GOOD_CA_DER],
            &anchors,
            Some("2027-01-01T00:00:00Z"),
        ) {
            ChainVerdict::Trusted { checks, .. } => {
                assert!(checks.validity_checked, "a clock was supplied");
                assert!(checks.constraints_checked, "constraints always checked");
                assert!(
                    !checks.revocation_checked,
                    "no-network: revocation never checked"
                );
            }
            other => panic!("expected Trusted, got {other:?}"),
        }
    }

    #[test]
    fn a_non_ca_intermediate_breaks_the_chain() {
        // leaf <- non-CA (basicConstraints CA:FALSE) <- root. The signatures all
        // verify, but a non-CA is not entitled to have signed a certificate, so
        // the chain is Untrusted (RFC 5280 4.2.1.9; Pass 10.5).
        let anchors = anchor_set(P105_ROOT_DER.to_vec());
        match evaluate(P105_LEAF_VIA_NONCA_DER, &[P105_NONCA_DER], &anchors, None) {
            ChainVerdict::Untrusted { reason } => {
                assert!(reason.contains("is not a CA"), "reason was: {reason}");
            }
            other => panic!("expected Untrusted (non-CA issuer), got {other:?}"),
        }
    }

