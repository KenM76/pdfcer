use crate::trust_store::TrustAnchorSet;

/// Maximum chain length walked before giving up (RFC 5280 chains are short; a
/// long one is hostile or malformed).
const MAX_DEPTH: usize = 16;

/// Which of the RFC 5280 path checks actually ran for a [`ChainVerdict`], so a
/// caller can disclose precisely what a `Trusted` result does and does not
/// assert (`Pass 10.5`; disclosure discipline, project rule 4).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PathChecks {
    /// Certificate validity dates were checked against a supplied clock. `false`
    /// means no reference time was available, so expiry was NOT verified.
    pub validity_checked: bool,
    /// `basicConstraints`/`keyUsage` were enforced on the intermediate issuers.
    /// Always `true` this build (the check is deterministic and unconditional).
    pub constraints_checked: bool,
    /// Certificate revocation (CRL/OCSP) was checked. Always `false` this build:
    /// revocation needs the network, which `pdfcer-core` never touches.
    pub revocation_checked: bool,
}

/// The outcome of evaluating a signer against a trust-anchor pool.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ChainVerdict {
    /// The signer chains, by valid signatures, to a trusted anchor. Carries the
    /// anchor's subject, its `/Source` tags (AATL/EUTL/ADBE), and a
    /// [`PathChecks`] recording which validity/constraint checks ran, all for
    /// disclosure.
    ///
    /// ★ Read `checks` before presenting this: revocation is never checked
    /// here, and validity is checked only when a clock was supplied.
    Trusted {
        /// The trusted anchor's subject the chain terminated at.
        anchor_subject: String,
        /// That anchor's `/Source` provenance (e.g. `["AATL"]`).
        source: Vec<String>,
        /// Which path checks ran (validity/constraints/revocation).
        checks: PathChecks,
    },
    /// The signer's certificate parsed, but the chain does not reach a trusted
    /// anchor — an incomplete chain, an untrusted self-signed root, or a link
    /// whose signature did not verify. `reason` says which.
    Untrusted {
        /// A human-readable reason (incomplete chain, untrusted root, …).
        reason: String,
    },
    /// The signer's certificate could not be parsed at all — trust cannot even
    /// be attempted. Distinct from `Untrusted` (a parsed-but-not-trusted signer).
    SignerUnparseable,
}

/// Evaluate `signer_der` against `anchors`, using `intermediates` (the other
/// certificates carried in the signature) to bridge the chain.
///
/// `now` is the reference clock for validity-date checking, as an ISO
/// `YYYY-MM-DDTHH:MM:SSZ` string (typically the signature's signing time — see
/// [`crate::cms::Certificate::not_before`]). When `Some`, every certificate in
/// the chain must be within its validity window at `now`; when `None`, validity
/// is not checked and [`PathChecks::validity_checked`] is `false`.
///
/// See the module docs for exactly what a [`ChainVerdict::Trusted`] does and
/// does not assert.
#[must_use]
pub fn evaluate(
    signer_der: &[u8],
    intermediates: &[&[u8]],
    anchors: &TrustAnchorSet,
    now: Option<&str>,
) -> ChainVerdict {
    let checks = PathChecks {
        validity_checked: now.is_some(),
        constraints_checked: true,
        revocation_checked: false,
    };
    let Some(signer) = cms::parse_certificate(signer_der) else {
        return ChainVerdict::SignerUnparseable;
    };

    // Index the anchors by subject DN, and parse them once. An anchor whose
    // cert does not parse is simply not a candidate.
    let mut anchor_by_subject: HashMap<Vec<u8>, (Certificate<'_>, &[String])> = HashMap::new();
    for a in &anchors.anchors {
        if let Some(cert) = cms::parse_certificate(&a.der) {
            anchor_by_subject.insert(cert.subject_der.to_vec(), (cert, a.sources.as_slice()));
        }
    }
    // Index the intermediates by subject DN.
    let mut inter_by_subject: HashMap<Vec<u8>, Certificate<'_>> = HashMap::new();
    for der in intermediates {
        if let Some(cert) = cms::parse_certificate(der) {
            inter_by_subject.insert(cert.subject_der.to_vec(), cert);
        }
    }

    let mut current = signer;
    let mut seen: std::collections::HashSet<Vec<u8>> = std::collections::HashSet::new();
    for _ in 0..MAX_DEPTH {
        if !seen.insert(current.subject_der.to_vec()) {
            return ChainVerdict::Untrusted {
                reason: "the certificate chain contains a cycle".to_owned(),
            };
        }
        // Validity dates (RFC 5280 §4.1.2.5), when a clock was supplied. Checked
        // for every certificate the walk touches, starting with the signer.
        if let Err(reason) = cert_valid_at(&current, now) {
            return ChainVerdict::Untrusted { reason };
        }
        // Prefer a trusted anchor as the issuer: if an anchor's subject matches
        // this cert's issuer AND it signed this cert, the chain is trusted.
        if let Some((anchor_cert, sources)) = anchor_by_subject.get(current.issuer_der) {
            if verify_cert_signature(&current, &anchor_cert.key) {
                // The anchor is trusted as configured, so its cA bit is not
                // re-litigated -- but an expired trust anchor is still not valid.
                if let Err(reason) = cert_valid_at(anchor_cert, now) {
                    return ChainVerdict::Untrusted { reason };
                }
                return ChainVerdict::Trusted {
                    anchor_subject: anchor_cert.subject.clone(),
                    source: sources.to_vec(),
                    checks,
                };
            }
            return ChainVerdict::Untrusted {
                reason: format!(
                    "a trusted anchor ({}) is named as the issuer, but its signature over the certificate did not verify",
                    anchor_cert.subject
                ),
            };
        }
        // A self-signed certificate (issuer == subject) that no anchor matched
        // is an untrusted ROOT -- do NOT fall through to the intermediate pool,
        // where it would find ITSELF as issuer and loop. This is checked before
        // the intermediate lookup for exactly that reason.
        if current.issuer_der == current.subject_der {
            return ChainVerdict::Untrusted {
                reason: format!(
                    "the chain ends at a self-signed root ({}) that is not in the trust store",
                    current.subject
                ),
            };
        }
        // Otherwise climb through an embedded intermediate.
        if let Some(issuer) = inter_by_subject.get(current.issuer_der) {
            if !verify_cert_signature(&current, &issuer.key) {
                return ChainVerdict::Untrusted {
                    reason: format!(
                        "an intermediate ({}) is named as the issuer, but its signature over the certificate did not verify",
                        issuer.subject
                    ),
                };
            }
            // An intermediate must be entitled to sign certificates (RFC 5280
            // §4.2.1.9/§4.2.1.3): cA TRUE and keyUsage not clearing keyCertSign.
            if let Err(reason) = issuer_may_sign_certs(issuer) {
                return ChainVerdict::Untrusted { reason };
            }
            current = issuer.clone();
            continue;
        }
        return ChainVerdict::Untrusted {
            reason: format!(
                "the chain is incomplete: no certificate for the issuer ({})",
                current.issuer
            ),
        };
    }
    ChainVerdict::Untrusted {
        reason: format!("the certificate chain is longer than {MAX_DEPTH} and was not followed"),
    }
}

/// Check `cert`'s validity window against the reference clock `now` (RFC 5280
/// §4.1.2.5). Returns `Err(reason)` if `now` falls outside `notBefore..notAfter`.
///
/// The comparison is lexical: [`cms::Certificate::not_before`]/`not_after` and
/// `now` are all the fixed-width ISO `YYYY-MM-DDTHH:MM:SSZ` form produced by
/// [`crate::asn1::time_value`], which sorts chronologically as text. When `now`
/// is `None`, or a date is absent/unparseable, the check passes (it cannot be
/// performed) — [`PathChecks::validity_checked`] records that it was skipped.
fn cert_valid_at(cert: &Certificate<'_>, now: Option<&str>) -> Result<(), String> {
    let Some(now) = now else { return Ok(()) };
    if let Some(nb) = cert.not_before.as_deref()
        && now < nb
    {
        return Err(format!(
            "certificate '{}' is not yet valid at the signing time (valid from {nb})",
            cert.subject
        ));
    }
    if let Some(na) = cert.not_after.as_deref()
        && now > na
    {
        return Err(format!(
            "certificate '{}' was expired at the signing time (expired {na})",
            cert.subject
        ));
    }
    Ok(())
}

/// Check that `cert` is entitled to sign other certificates as an intermediate
/// CA (RFC 5280 §4.2.1.9 `basicConstraints`, §4.2.1.3 `keyUsage`). Returns
/// `Err(reason)` if it is not a CA, or if its `keyUsage` explicitly clears
/// `keyCertSign`. A `keyUsage` that is simply absent is not disqualifying.
fn issuer_may_sign_certs(cert: &Certificate<'_>) -> Result<(), String> {
    if !cert.is_ca {
        return Err(format!(
            "the issuer '{}' is not a CA (basicConstraints cA is not TRUE), so it cannot sign certificates",
            cert.subject
        ));
    }
    if cert.key_usage_cert_sign == Some(false) {
        return Err(format!(
            "the issuer '{}' has a keyUsage that forbids certificate signing (keyCertSign is not set)",
            cert.subject
        ));
    }
    Ok(())
}

/// Verify that `cert` was signed by the key `issuer_key` — hash `cert.tbs_der`
/// under the algorithm `cert.sig_alg_oid` names and check `cert.sig_value`.
///
/// Supports RSA PKCS#1 v1.5 (SHA-1/256/384/512), RSASSA-PSS (params from the
/// certificate's `signatureAlgorithm`, RFC 4055 — `Pass 10.5`), and ECDSA
/// (SHA-1/256/384/512). Any other algorithm is declined (returns `false`) —
/// declining is the safe direction (it can only fail to trust, never falsely
/// trust).
fn verify_cert_signature(cert: &Certificate<'_>, issuer_key: &PublicKey<'_>) -> bool {
    let Some(sig_alg) = cert.sig_alg.as_ref() else {
        return false;
    };
    let alg = sig_alg.oid.as_str();
    // RSASSA-PSS is params-dependent (hash, MGF hash, salt length live in the
    // AlgorithmIdentifier's parameters), so it is handled before the fixed
    // OID→hash table below (Pass 10.5).
    if alg == oid::RSASSA_PSS {
        let PublicKey::Rsa { n, e } = issuer_key else {
            return false;
        };
        let Ok((hash, mgf_hash, salt_len)) = crate::signature_verify::pss_params(sig_alg) else {
            return false;
        };
        let digest = hash.digest(cert.tbs_der);
        let rsa = RsaPublicKey {
            n: Uint::from_be_bytes(n),
            e: Uint::from_be_bytes(e),
        };
        return rsa.verify_pss(hash, mgf_hash, salt_len, &digest, cert.sig_value);
    }
    let hash = match alg {
        oid::SHA1_WITH_RSA | oid::ECDSA_SHA1 => Hash::Sha1,
        oid::SHA256_WITH_RSA | oid::ECDSA_SHA256 => Hash::Sha256,
        oid::SHA384_WITH_RSA | oid::ECDSA_SHA384 => Hash::Sha384,
        oid::SHA512_WITH_RSA | oid::ECDSA_SHA512 => Hash::Sha512,
        // RSA-PSS (params-dependent) and unknowns: decline, conservatively.
        _ => return false,
    };
    let digest = hash.digest(cert.tbs_der);
    let is_rsa = matches!(
        alg,
        oid::SHA1_WITH_RSA | oid::SHA256_WITH_RSA | oid::SHA384_WITH_RSA | oid::SHA512_WITH_RSA
    );
    match issuer_key {
        PublicKey::Rsa { n, e } if is_rsa => {
            let rsa = RsaPublicKey {
                n: Uint::from_be_bytes(n),
                e: Uint::from_be_bytes(e),
            };
            rsa.verify_pkcs1v15(hash, &digest, cert.sig_value)
        }
        PublicKey::Ec { curve_oid, point } if !is_rsa => {
            let Some(curve) = Curve::from_oid(curve_oid) else {
                return false;
            };
            let Some(key) = EcPublicKey::from_sec1(curve, point) else {
                return false;
            };
            // ECDSA-Sig-Value ::= SEQUENCE { r INTEGER, s INTEGER }.
            let Some((seq, _)) = asn1::expect(cert.sig_value, asn1::SEQUENCE) else {
                return false;
            };
            let parts = asn1::children(seq).unwrap_or_default();
            let (Some(r), Some(s)) = (
                parts.first().and_then(|t| asn1::integer_bytes(*t)),
                parts.get(1).and_then(|t| asn1::integer_bytes(*t)),
            ) else {
                return false;
            };
            key.verify(&digest, r, s)
        }
        // Key type does not match the signature algorithm.
        _ => false,
    }
}

