//! # Variable-text appearance generation (ISO 32000-1 §12.7.3.3)
//!
//! The **hardest single piece of appearance generation**, isolated into
//! Pass 6.2 so Pass 7 (Forms) inherits a proven generator. Where
//! [`crate::annot_author`] turns *geometry* into an `/AP` `/N` form
//! XObject, this module turns *text* into one: given a text value, a `/DA`
//! default-appearance string, a `/Q` quadding code, and a resource set, it
//! produces the `/Tx BMC … EMC` marked-content body §12.7.3.3 specifies
//! (Figure — the verbatim EXAMPLE in the clause), authored in Base-14
//! metrics with **no embedded font program** (§9.6.2.1 — see
//! [`standard14_font_dict`]).
//!
//! It is a **single pipeline shared by FreeText and text widgets**
//! (`iso32000__s__12.7.3.3.md`): a FreeText `/AP` and a variable-text
//! widget `/AP` are generated by the same `/DA` + `/Q` + value code; only
//! the resource-resolution *root* differs (FreeText resolves the `/DA`
//! font name against the annotation's own `/AP` `/Resources`; a widget
//! against the `/AcroForm` `/DR`). This module parameterizes the root as a
//! `&[FontResource]` and is unaware of which caller supplied it.
//!
//! ## Spec facts this module enacts (from `iso32000__s__12.7.3.3.md`)
//!
//! - **`/DA` is parsed with the REAL content lexer (risk X9).** A `/DA`
//!   string is a *content-stream fragment stored in a PDF string* — it can
//!   carry names, reals, arrays and operators, so a split-on-space scanner
//!   misparses it. [`parse_default_appearance`] runs
//!   [`ContentStream::parse`](crate::content::ContentStream::parse) over
//!   the `/DA` bytes and reads the operators back out — never an ad-hoc
//!   scan.
//! - **The only `shall`-minimum is `Tf`** (font + size). Colour is *not*
//!   required (VT2): absent, text renders in the graphics-state default
//!   `0 g` black. A `/DA` with no `Tf` is [`VarTextError::MissingTf`].
//! - **A font the resource set does not carry is a NAMED refusal**
//!   ([`VarTextError::FontUnresolved`]), never a silent substitution — a
//!   substituted font changes glyph advances, so what the operator sees
//!   would differ from what every other reader sees.
//! - **At most one `Tm`** (VT4): more than one is
//!   [`VarTextError::TooManyTm`]. This generator authors **zero** `Tm` in
//!   the `/DA` and emits exactly one in the body to set the first line's
//!   origin, positioning later lines with `Td` (which is not a `Tm`).
//! - **`size = 0` ⇒ auto-size** (VT1). The spec mandates *that* auto-size
//!   happens ("a function of the height of the annotation rectangle") but
//!   gives **no formula** — so [`auto_size`] is a *reviewable pdfcer
//!   heuristic* (fuzzy-never-sneaky, rule 4), and every appearance that
//!   applied it reports the size it chose ([`VarTextAppearance::applied_autosize`]).
//! - **`BBox = [0 0 Rect_w Rect_h]`, identity `Matrix`.** The body is laid
//!   out in `[0,0]–[W,H]` local coordinates and placed 1:1 into the
//!   annotation `/Rect` by §12.5.5 with no scale (the §8.10 W-B
//!   anti-distortion pattern). The clip is that same box.
//! - **`/RC` rich text is an EXPLICIT non-goal** (VT3): this module
//!   authors *plain* text only. Recognition/round-trip of `/RC`/`/RV`/
//!   `/DS` lives at the annotation layer, not here.
//!
//! ## Font resourcing — Base-14, no embedded program (§9.6.2.1)
//!
//! §9.6.2.1 Table 111 marks `Widths`/`FontDescriptor` "Required **except
//! for the standard 14 fonts**", and for those they "shall either all be
//! present or all be absent". `FontDescriptor` is the sole carrier of the
//! embedded program (§9.8), so a standard-14 dict may omit it and the
//! reader supplies the glyphs (§9.6.2.2). [`standard14_font_dict`]
//! therefore authors a minimal dict with **zero font bytes**, and pdfcer's
//! own renderer paints it through its bundled Foxit substitute face
//! (`pdfcer-render::font::select::by_name`). The `/Q` measurement uses the
//! compiled APAFML advance widths already in [`crate::fontdata`] — all
//! GUI-free, on the correct side of the §3 invariant (decision 008 F5).
//!
//! **Modality choice (recorded, not a blocker):** PDF 1.5+ *deprecates*
//! the bare standard-14 form — writers *should* embed a full descriptor —
//! but readers *shall* still honour the bare form (§9.6.2.1). pdfcer
//! deliberately authors the bare form (universally reader-supported, no
//! font-program bytes to reproduce on round-trip), adding only
//! `/Encoding /WinAnsiEncoding` so byte→glyph is deterministic for Latin
//! text (the same encoding [`measure`] assumes). This is a `should`
//! deviation on the write side and a fully conformant document on the
//! read side.
//!
//! ## Named limits (Base-14 Latin only — R17, no `harfrust`)
//!
//! - **No complex-script / RTL shaping.** Text is laid out left-to-right,
//!   one glyph per `WinAnsi` byte (R17 keeps `harfrust` unshipped — this
//!   is the first text-*authoring* path decision 004 reserved for it, and
//!   it is built without it). Non-Latin scripts are out of scope.
//! - **A character with no `WinAnsi` code is substituted with `?` and
//!   COUNTED** ([`VarTextAppearance::unencodable_chars`]) — disclosed, not
//!   silently dropped (fuzzy-never-sneaky).

