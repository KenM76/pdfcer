    /// A `/P` that disagrees with the encrypted copy is reported with **both**
    /// numbers, so a caller can show the operator what disagrees rather than
    /// only that something does.
    #[test]
    fn a_tampered_p_is_reported_with_both_values() {
        match validate_perms(&FILE_KEY, &PERMS, 0xFFFF_FFFF, true) {
            PermsCheck::Mismatch {
                perms_p,
                dict_p,
                perms_encrypt_metadata,
                dict_encrypt_metadata,
            } => {
                assert_eq!(perms_p, DICT_P, "the encrypted copy is unchanged");
                assert_eq!(dict_p, 0xFFFF_FFFF, "the plaintext copy is what moved");
                assert_eq!(perms_encrypt_metadata, Some(true));
                assert!(dict_encrypt_metadata);
            }
            other => unreachable!("expected a mismatch, got {other:?}"),
        }
    }

    /// An `/EncryptMetadata` that disagrees is a mismatch too — byte 8 is part
    /// of the protected block, not decoration.
    #[test]
    fn a_flipped_encrypt_metadata_is_a_mismatch() {
        assert!(matches!(
            validate_perms(&FILE_KEY, &PERMS, DICT_P, false),
            PermsCheck::Mismatch { .. }
        ));
    }

    /// A `/Perms` that does not decrypt to the `adb` marker is
    /// [`PermsCheck::MarkerMissing`], not a mismatch. The two mean different
    /// things — "someone changed the numbers" versus "these bytes are not a
    /// permissions block at all" — and collapsing them would report tampering
    /// for a corrupted file.
    #[test]
    fn a_corrupt_perms_block_reports_the_missing_marker() {
        let mut damaged = PERMS;
        damaged[0] ^= 0xFF;
        assert_eq!(
            validate_perms(&FILE_KEY, &damaged, DICT_P, true),
            PermsCheck::MarkerMissing
        );
    }

    /// ★ Falsification: `/Perms` is **ECB**, and giving it CBC's treatment
    /// destroys it.
    ///
    /// `unwrap_key_cbc_256` is CBC with a zero IV — the closest neighbouring
    /// mode, and the one an implementation is most likely to reach for by
    /// accident since it is right there and takes the same key. Over a single
    /// block the two differ by an XOR with the zero IV… which is a no-op, so
    /// they *agree*. The test therefore uses a **non-zero** IV's worth of
    /// difference by decrypting the block as if it were the second block of a
    /// two-block CBC message, which is what happens the moment `/Perms` is
    /// routed through a general CBC path with real preceding data.
    #[test]
    fn perms_decrypted_as_chained_cbc_loses_its_marker() {
        // Two blocks: some arbitrary "previous" ciphertext, then /Perms. Under
        // CBC the second block is XORed with the first block's ciphertext.
        let mut chained = [0u8; 32];
        chained[..16].copy_from_slice(&[0xAA; 16]);
        chained[16..].copy_from_slice(&PERMS);
        let out = unwrap_key_cbc_256(&FILE_KEY, &chained);
        assert_eq!(out.len(), 32);
        assert_ne!(
            &out[16 + 9..16 + 12],
            b"adb",
            "chaining must corrupt the marker; if it does not, this test is \
             not observing the difference it claims to"
        );
        // ECB, correctly, does not.
        assert_eq!(&decrypt_ecb_256_block(&FILE_KEY, &PERMS)[9..12], b"adb");
    }

