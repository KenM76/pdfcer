//! `/R` 5 — the AES-256 password and key algorithms (Adobe Supplement to ISO
//! 32000, BaseVersion 1.7, ExtensionLevel 3, June 2008, §3.5, Algorithms 3.2a
//! and 3.8–3.13).
//!
//! # What this module is
//!
//! Everything that turns a **password** into the 32-byte **file encryption
//! key** at `/V` 5, plus the one integrity check PDF encryption has. It is the
//! `/R` 5 counterpart of [`standard`](super::standard)'s Algorithms 2, 3, 6 and
//! 7, and it shares *nothing* with them: no MD5, no padding string, no 50-round
//! loop, no `/ID[0]`, no per-object step. The supplement says so directly —
//! **"encrypt version 5 does not use MD5"** — and the key is decoupled from the
//! password entirely, generated by the producer's RNG and then *wrapped* under
//! a password-derived key. That decoupling is why one document has two
//! independent passwords that both recover the same key.
//!
//! # Sourcing, and why `/R` 6 is not here
//!
//! `license_basis: free_secondary_paraphrase`. Adobe's ExtensionLevel 3
//! supplement is freely downloadable and **all rights reserved**, so the
//! project's corpus paraphrases it into step form rather than quoting it; the
//! same posture it takes for Adobe TN #5004. Source file:
//! `D:\Dev\Rag-Specialized\PDF_Spec\security\security__aes256_r5_r6.md`.
//!
//! **`/R` 6 is refused, and this module is not a step towards implementing
//! it.** `/R` 6 uses the identical harness — same 48-byte `/O` and `/U`, same
//! two 8-byte salts, same zero-IV `/UE`/`/OE` unwrap, same 16-byte `/Perms` —
//! with **Algorithm 2.B substituted for `SHA-256(...)` at every position**.
//! Algorithm 2.B was sourced from the ISO 32000-2:2020 primary on 2026-08-12 —
//! its inner AES-128-CBC step, its SHA-256/384/512 selector, its round count
//! and its termination condition — and is implemented in [`super::r6`]. The
//! substitution point IS a pluggable seam ([`Hasher`], `Pass 5.4`): `/R` 5
//! passes [`Hasher::Sha256`] and `/R` 6 passes [`Hasher::R6`], and every
//! auth/key function below takes one. `enc-aes-256-r6.pdf` is now a
//! **decryption** fixture (it opens), and pdfcer's own `/R` 6 writer is
//! cross-checked against pypdf.
//!
//! # The layout everything depends on
//!
//! `/O` and `/U` are **48 bytes** at `/R` 5, three concatenated sections:
//!
//! ```text
//! byte  0 .. 31   32-byte hash          <- what a password is checked against
//! byte 32 .. 39    8-byte Validation Salt  <- salts the check
//! byte 40 .. 47    8-byte Key Salt         <- salts the key that unwraps UE/OE
//! ```
//!
//! Nothing marks this layout. A 32-byte `/U` means `/R` ≤ 4 and a 48-byte
//! `/U` means `/R` ≥ 5 — **length is the only discriminator there is**, and a
//! file claiming `/R` 5 with a 32-byte `/U` has no stated recovery. This module
//! takes fixed-size arrays so that question is answered once, at parse time,
//! by [`EncryptionConfig::parse`](super::standard::EncryptionConfig::parse).
//!
//! # The four traps
//!
//! - **T24 — no per-object key.** The recovered key is used *as-is* for every
//!   string and stream. Handled in
//!   [`FileKey::object_key`](super::standard::FileKey::object_key); named here
//!   because this module is where the key is born.
//! - **T25 — three AES modes.** See [`aes`](super::aes)'s module docs. This
//!   module uses two of them: zero-IV/no-padding CBC to unwrap, ECB for
//!   `/Perms`.
//! - **T26 — the owner algorithms concatenate the WHOLE 48-byte `/U`**, not
//!   its 32-byte hash. Both in [`authenticates_as_owner`] and in
//!   [`file_key_from_owner_password`]. Passing 32 bytes there is a one-line
//!   slip that fails only for owner passwords, i.e. in the branch that has no
//!   fixture unless somebody wrote one.
//! - **T27 — `/Perms` is a check, not a source of truth**, and the spec's
//!   verdict on a mismatch is `should`, not `shall`. See [`PermsCheck`].
//!
//! # A source-text defect this module deliberately does not follow
//!
//! Algorithm 3.12's own concluding sentence says the password it validated is
//! "the **user** password". It is the **owner** password — the algorithm's
//! title, its inputs and its position in 3.2a all say so, and the corpus
//! records the defect as ambiguity **A10** (verified 2026-07-31 against the
//! staged PDF). [`authenticates_as_owner`] implements the algorithm, not its
//! closing sentence.

use sha2::{Digest, Sha256};

use crate::crypto::aes::{KEY_LEN_256, decrypt_ecb_256_block, unwrap_key_cbc_256};

/// Length of `/O` and `/U` at `/R` 5 (Table 3.19). 32-byte hash + two 8-byte
/// salts.
pub const OU_LEN: usize = 48;

/// Length of `/OE` and `/UE` (Table 3.19) — one wrapped 32-byte file
/// encryption key, exactly two AES blocks, no padding.
pub const OE_UE_LEN: usize = KEY_LEN_256;

/// Length of `/Perms` (Table 3.19) — one AES block.
pub const PERMS_LEN: usize = 16;

/// Byte range of the 32-byte hash inside a 48-byte `/O` or `/U`.
const HASH: std::ops::Range<usize> = 0..32;
/// Byte range of the 8-byte Validation Salt inside a 48-byte `/O` or `/U`.
const VALIDATION_SALT: std::ops::Range<usize> = 32..40;
/// Byte range of the 8-byte Key Salt inside a 48-byte `/O` or `/U`.
const KEY_SALT: std::ops::Range<usize> = 40..48;

/// The maximum number of **bytes** of UTF-8 password `/R` 5 hashes.
///
/// Step 3 of the supplement's password preprocessing: "truncate to the first
/// 127 bytes if longer". Bytes, not characters — a 127-byte truncation can
/// land mid-sequence in UTF-8, and the algorithm does not care. Compare
/// [`pad_password`](super::standard::pad_password)'s 32 at `/R` ≤ 4, which
/// pads as well as truncates; there is no padding at all here.
pub const MAX_PASSWORD_LEN: usize = 127;

/// The `/R` 5 hash: plain SHA-256 over the concatenated parts.
///
/// ★ **This function is Algorithm 2.B's substitution point.** At `/R` 6 every
/// call site below uses 2.B in place of this, with identical inputs and an
/// identical 32-byte output, and *nothing else* about `/R` 5 changes. The
/// corpus is explicit about that (`iso32000__delta__pdf20_encryption.md` §6),
/// and it is recorded here so a future session does not re-derive the shape of
/// the gap. 2.B's body is now sourced and implemented ([`super::r6`], `Pass 5.4`).
/// Which hash `/R` 5 and `/R` 6 use — the ONE thing that differs between the
/// two revisions (`Pass 5.4`). `/R` 5 is plain SHA-256; `/R` 6 is Algorithm
/// 2.B ([`super::r6`]). Every auth/key function below takes one of these and is
/// otherwise identical across the two revisions.
///
/// `input_parts` is the sequence `/R` 5 SHA-256s (e.g. `[password, salt]`);
/// `password` is repeated because 2.B needs it separately inside `K0`; `u` is
/// the 48-byte `/U` on the owner paths only. For [`Hasher::Sha256`] the
/// `password` argument is ignored (the password is already `input_parts[0]`)
/// and `u`, when present, is appended — reproducing the `/R` 5 concatenation
/// exactly.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Hasher {
    /// `/R` 5 — plain SHA-256 over the concatenated parts (then `u`).
    Sha256,
    /// `/R` 6 — Algorithm 2.B, at the given [`super::r6::A13Reading`].
    R6(super::r6::A13Reading),
}

impl Hasher {
    /// The 32-byte hash this revision computes from the given inputs.
    #[must_use]
    pub fn hash(self, input_parts: &[&[u8]], password: &[u8], u: Option<&[u8]>) -> [u8; 32] {
        match self {
            Self::Sha256 => {
                let mut h = Sha256::new();
                for p in input_parts {
                    h.update(p);
                }
                if let Some(u) = u {
                    h.update(u);
                }
                h.finalize().into()
            }
            Self::R6(reading) => {
                // The full input concatenation is `input_parts ‖ u` — U is part
                // of the OWNER input string (Algorithm 2.A(c)/12), exactly as
                // SHA-256 appends it above. 2.B ADDITIONALLY feeds U into every
                // K0 (its step (a)), so `u` is passed on BOTH — proven against
                // pypdf's `/O`: U in the input string alone does not match, U in
                // both does.
                let mut input: Vec<u8> = input_parts.concat();
                if let Some(u) = u {
                    input.extend_from_slice(u);
                }
                super::r6::hash_2b(&input, password, u, reading)
            }
        }
    }
}

/// A password prepared for `/R` 5 hashing, and an honest note about how far
/// the preparation got.
///
/// # The preprocessing the supplement asks for, and what pdfcer does
///
/// Three steps:
///
/// 1. Apply the **SASLprep** profile (RFC 4013) of **stringprep** (RFC 3454),
///    with the Normalize and BIDI options.
/// 2. Convert to **UTF-8**.
/// 3. **Truncate to the first 127 bytes.**
///
/// pdfcer implements steps 2 and 3 exactly. It does **not** implement step 1,
/// and does not pretend to: neither RFC is staged in the project's spec
/// corpus, and a stringprep dependency is not being taken for a read-only
/// increment.
///
/// **For an all-ASCII password SASLprep is the identity function**, so for
/// every password a person can type on an unshifted keyboard, steps 2 and 3
/// *are* the whole algorithm and the result is exact. That covers the fixtures
/// and, on any realistic prior, the overwhelming majority of real documents.
///
/// # Why a non-ASCII password is attempted rather than refused
///
/// The tempting alternative is to refuse a non-ASCII password by name. It was
/// rejected, because it is *worse* on both sides of the coin:
///
/// - SASLprep is the identity for far more than ASCII — an already-normalised,
///   direction-neutral string passes through unchanged — so refusing rejects
///   passwords that would have worked, with no way for the operator to
///   discover that they would have.
/// - Getting normalisation wrong here **cannot** produce a silently wrong
///   result. Authentication is self-verifying: the SHA-256 either equals
///   `/U[0..32]` or it does not. A mis-normalised password fails to
///   authenticate; it never opens a document with a wrong key. This is the
///   opposite of the usual fuzzy-never-sneaky hazard, where an inference gets
///   *used*.
///
/// So the only harm a missing SASLprep can do is a **false "wrong password"**,
/// and the fix for that is a diagnostic, not a refusal. [`needs_saslprep`]
/// reports whether this password could have been changed by step 1;
/// `document.rs` turns a failed authentication on such a password into a
/// distinct error that says so, instead of the flat "supply the password"
/// every wrong guess produces. Rule 4 is satisfied by disclosure, not by
/// declining to try.
///
/// [`needs_saslprep`]: Self::needs_saslprep
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PreparedPassword {
    /// The UTF-8 bytes, truncated to [`MAX_PASSWORD_LEN`].
    bytes: Vec<u8>,
    /// Whether the input contained any byte SASLprep could act on.
    needs_saslprep: bool,
    /// Whether step 3 actually removed anything.
    truncated: bool,
}

impl PreparedPassword {
    /// Prepare `password` for hashing.
    ///
    /// `password` is taken as bytes rather than as `&str` because that is what
    /// reaches pdfcer: a CLI argument, a password file, a GUI text box, all of
    /// which may hold something that is not valid UTF-8. Step 2 ("convert to
    /// UTF-8") is therefore a no-op on already-UTF-8 input and a
    /// pass-the-bytes-through on anything else — inventing a re-encoding for
    /// invalid input would be guessing at the producer's intent, and the
    /// supplement offers no branch for it.
    #[must_use]
    pub fn new(password: &[u8]) -> Self {
        // A byte is "SASLprep-relevant" if step 1 could map, prohibit or
        // reorder it. Every ASCII graphic character and the space are mapped
        // to themselves, so only the non-ASCII range (0x80..) and the ASCII
        // C0 controls can be affected. Controls are *prohibited* output by
        // RFC 4013 rather than mapped, but the honest report is the same: this
        // password is one pdfcer cannot promise it prepared correctly.
        let needs_saslprep = password
            .iter()
            .any(|&b| b >= 0x80 || (b.is_ascii_control() && b != b' '));

        let take = password.len().min(MAX_PASSWORD_LEN);
        Self {
            // `get(..take)` rather than an index: `take` is `min`-clamped, so
            // this cannot fail, and the fallback keeps the proof local in a
            // function that handles untrusted input.
            bytes: password.get(..take).unwrap_or_default().to_vec(),
            needs_saslprep,
            truncated: password.len() > MAX_PASSWORD_LEN,
        }
    }

    /// The bytes to hash.
    #[must_use]
    pub fn as_bytes(&self) -> &[u8] {
        &self.bytes
    }

    /// Whether SASLprep (step 1), which pdfcer does not implement, could have
    /// changed this password.
    ///
    /// `false` means the preparation is **exact** and a failed authentication
    /// is simply a wrong password. `true` means a failure is ambiguous and
    /// must be reported as such — see the type's docs.
    #[must_use]
    pub fn needs_saslprep(&self) -> bool {
        self.needs_saslprep
    }

    /// Whether step 3's 127-byte truncation removed anything.
    ///
    /// Reported because it is otherwise invisible: two passwords sharing their
    /// first 127 bytes are the *same* password to this algorithm, which is a
    /// surprising fact worth being able to state rather than a bug.
    #[must_use]
    pub fn was_truncated(&self) -> bool {
        self.truncated
    }
}

/// Algorithm 3.11 — does `password` authenticate as the **user** password?
///
/// `SHA-256(password ‖ UserValidationSalt)` equals `/U[0..32]`.
///
/// Note what is *not* an input: `/ID[0]` (which Algorithms 2 and 5 hash at
/// `/R` ≤ 4), `/P`, `/O`, and `/EncryptMetadata`. At `/R` 5 the user check
/// depends on nothing but the password and eight bytes of salt, which is
/// precisely why the `/Perms` check exists — see [`PermsCheck`].
#[must_use]
pub fn authenticates_as_user(
    password: &PreparedPassword,
    u: &[u8; OU_LEN],
    hasher: Hasher,
) -> bool {
    // Ranges are compile-time constants over a fixed-size array, so every
    // index below is in bounds by the type.
    #[allow(clippy::indexing_slicing)]
    let (expect, salt) = (&u[HASH], &u[VALIDATION_SALT]);
    hasher.hash(&[password.as_bytes(), salt], password.as_bytes(), None) == expect
}

/// Algorithm 3.12 — does `password` authenticate as the **owner** password?
///
/// `SHA-256(password ‖ OwnerValidationSalt ‖ U)` equals `/O[0..32]`, where `U`
/// is the **whole 48-byte `/U` string** (**T26**) — not its 32-byte hash, and
/// not `/U` at all if you were reading Algorithm 3.11 a moment ago.
///
/// The concatenation is what makes the two passwords independent while both
/// recover the same key: `/O` is bound to `/U`, so `/U` must be computed
/// first on the writer side, and an owner check cannot be performed without
/// the user string in hand.
#[must_use]
pub fn authenticates_as_owner(
    password: &PreparedPassword,
    o: &[u8; OU_LEN],
    u: &[u8; OU_LEN],
    hasher: Hasher,
) -> bool {
    #[allow(clippy::indexing_slicing)]
    let (expect, salt) = (&o[HASH], &o[VALIDATION_SALT]);
    hasher.hash(&[password.as_bytes(), salt], password.as_bytes(), Some(u)) == expect
}

/// Algorithm 3.2a, user branch — recover the file encryption key from `/UE`.
///
/// Unwrap key = `SHA-256(password ‖ UserKeySalt)`; that key decrypts `/UE`
/// with **AES-256-CBC, zero IV, no padding** (see
/// [`unwrap_key_cbc_256`]) to give the 32-byte
/// file encryption key.
///
/// **The Key Salt is a different eight bytes from the Validation Salt.**
/// Transposing them is the classic slip here and it is *not* silent in the
/// helpful sense: authentication still passes (it uses the validation salt via
/// [`authenticates_as_user`]) and the recovered key is then wrong, so the
/// document opens and decrypts to noise. Only an end-to-end fidelity check
/// catches it.
///
/// # Returns
///
/// `None` if the unwrap did not yield exactly 32 bytes, which for a
/// well-formed 32-byte `/UE` cannot happen — the check exists so a malformed
/// `/UE` cannot produce a short "key" that silently decrypts nothing.
#[must_use]
pub fn file_key_from_user_password(
    password: &PreparedPassword,
    u: &[u8; OU_LEN],
    ue: &[u8; OE_UE_LEN],
    hasher: Hasher,
) -> Option<[u8; KEY_LEN_256]> {
    #[allow(clippy::indexing_slicing)]
    let salt = &u[KEY_SALT];
    let unwrap_key = hasher.hash(&[password.as_bytes(), salt], password.as_bytes(), None);
    unwrap_key_cbc_256(&unwrap_key, ue).try_into().ok()
}

/// Algorithm 3.2a, owner branch — recover the file encryption key from `/OE`.
///
/// Unwrap key = `SHA-256(password ‖ OwnerKeySalt ‖ U)`, again over the **whole
/// 48-byte `/U`** (**T26**); that key decrypts `/OE` the same way. The result
/// is the *same* 32-byte file encryption key the user branch produces — the
/// two wrapped copies exist so either password recovers it, which is the whole
/// reason `/R` 5 decoupled the key from the password in the first place.
///
/// # Returns
///
/// `None` on a malformed `/OE`; see [`file_key_from_user_password`].
#[must_use]
pub fn file_key_from_owner_password(
    password: &PreparedPassword,
    o: &[u8; OU_LEN],
    u: &[u8; OU_LEN],
    oe: &[u8; OE_UE_LEN],
    hasher: Hasher,
) -> Option<[u8; KEY_LEN_256]> {
    #[allow(clippy::indexing_slicing)]
    let salt = &o[KEY_SALT];
    let unwrap_key = hasher.hash(&[password.as_bytes(), salt], password.as_bytes(), Some(u));
    unwrap_key_cbc_256(&unwrap_key, oe).try_into().ok()
}

/// The verdict of Algorithm 3.13 — the **only integrity check in PDF
/// encryption** (negative result **N7**).
///
/// # Why this is reported and never acted on (T27)
///
/// `/Perms` is a 16-byte block holding an encrypted copy of `/P` and of
/// `/EncryptMetadata`. At `/V` 1–4 those values sit in the file as editable
/// plaintext with no protection at all; `/Perms` is the one place PDF binds
/// them to the encryption key. That makes it the only thing in clause 7.6 that
/// can detect tampering — and the supplement still states its verdict as
/// **`should` match**, with **no clause anywhere saying what to do when it
/// does not**.
///
/// pdfcer therefore **reports the disagreement and prefers neither value**:
///
/// - It does **not refuse the document.** The spec's modality is `should`, and
///   every other reader opens the file; refusing would make pdfcer reject
///   documents nothing else objects to, on the strength of a check the
///   standard declines to require.
/// - It does **not silently substitute** the decrypted `/P` for the
///   dictionary's. That is exactly the shape rule 4 forbids: a value pdfcer
///   *inferred* to be more trustworthy, becoming what the operator is shown,
///   with no disclosure. [`Permissions`](super::standard::Permissions) keeps
///   reporting the dictionary `/P` — the value the file declares and the value
///   every other viewer displays — and the disagreement is surfaced beside it
///   through [`DocumentEncryption::perms`].
/// - It does **not** treat a mismatch as damage. [`Self::MarkerMissing`] is
///   the case that means "the decryption itself is suspect", and it is kept
///   distinct for that reason.
///
/// [`DocumentEncryption::perms`]: crate::document::DocumentEncryption::perms
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PermsCheck {
    /// There is no `/Perms` entry to check. `/R` ≤ 4 has none — the entry was
    /// introduced by ExtensionLevel 3 — so this is the ordinary answer for
    /// every RC4 and AES-128 document, and is **not** a negative result.
    NotApplicable,
    /// Decrypted cleanly, the `adb` marker is present, and both recovered
    /// values agree with the plaintext dictionary.
    Match,
    /// Decrypted cleanly and the `adb` marker is present, but a recovered
    /// value disagrees with the dictionary.
    ///
    /// The most likely innocent cause is a producer that edited `/P` without
    /// re-encrypting `/Perms`; the most likely non-innocent one is someone
    /// widening the permissions of a document they could not decrypt.
    /// **Nothing in the file distinguishes those**, which is precisely why
    /// pdfcer reports rather than decides.
    Mismatch {
        /// Bytes 0–3 of the decrypted block, little-endian: the permission
        /// flags as the *encrypting producer* recorded them.
        perms_p: u32,
        /// `/P` as it sits in the `/Encrypt` dictionary, unsigned (T10).
        dict_p: u32,
        /// Byte 8: `Some(true)` for ASCII `'T'`, `Some(false)` for `'F'`,
        /// `None` for anything else — a third state the algorithm does not
        /// define and which must not be collapsed into `false`.
        perms_encrypt_metadata: Option<bool>,
        /// `/EncryptMetadata` as the dictionary states it (default `true`).
        dict_encrypt_metadata: bool,
    },
    /// Decrypted, but bytes 9–11 are not the literal `adb`.
    ///
    /// A different fact from [`Self::Mismatch`]: the marker is a fixed
    /// constant, so its absence means the *decryption* is wrong — a truncated
    /// or corrupted `/Perms`, or a file encryption key that is not the one
    /// this document was encrypted with. Since authentication has already
    /// succeeded by the time this runs, in practice it points at a damaged
    /// `/Perms` rather than at a wrong password.
    MarkerMissing,
}

/// Algorithm 3.13 — decrypt `/Perms` and compare it with the dictionary.
///
/// `file_key` is the recovered file encryption key; `perms` is the raw 16-byte
/// `/Perms` string; `dict_p` and `dict_encrypt_metadata` are the plaintext
/// values from the `/Encrypt` dictionary.
///
/// The decrypted block's layout (Algorithm 3.10):
///
/// | Bytes | Content |
/// |---|---|
/// | 0–3 | the permission flags, **little-endian** |
/// | 4–7 | `FF FF FF FF` — `/P` extended to 64 bits with the high half all 1s |
/// | 8 | ASCII `'T'` or `'F'`, the `/EncryptMetadata` boolean |
/// | 9–11 | ASCII `'a'`, `'d'`, `'b'` — the marker |
/// | 12–15 | random, **"which will be ignored"** |
///
/// Bytes 4–7 are *not* checked. The supplement's own note explains why they
/// are all 1s — "this allows for future extension without changing the
/// format" — so a future revision could put something there, and asserting on
/// them would turn a forward-compatible file into a reported mismatch. Bytes
/// 12–15 are likewise ignored, and are the reason `/Perms` can never be
/// re-derived on save: it must be preserved verbatim (**R33**), exactly like
/// `/U`'s arbitrary tail at `/R` ≥ 3 (**T15**).
///
/// # Returns
///
/// See [`PermsCheck`]. This function never fails and never decides anything —
/// it is a report.
#[must_use]
#[allow(clippy::indexing_slicing)]
pub fn validate_perms(
    file_key: &[u8; KEY_LEN_256],
    perms: &[u8; PERMS_LEN],
    dict_p: u32,
    dict_encrypt_metadata: bool,
) -> PermsCheck {
    // Every index below is a constant into a fixed 16-byte array.
    let out = decrypt_ecb_256_block(file_key, perms);

    if &out[9..12] != b"adb" {
        return PermsCheck::MarkerMissing;
    }

    let perms_p = u32::from_le_bytes([out[0], out[1], out[2], out[3]]);
    let perms_encrypt_metadata = match out[8] {
        b'T' => Some(true),
        b'F' => Some(false),
        _ => None,
    };

    if perms_p == dict_p && perms_encrypt_metadata == Some(dict_encrypt_metadata) {
        PermsCheck::Match
    } else {
        PermsCheck::Mismatch {
            perms_p,
            dict_p,
            perms_encrypt_metadata,
            dict_encrypt_metadata,
        }
    }
}

