    /// Step 3: 127 **bytes**, and the truncation is reported.
    #[test]
    fn passwords_are_truncated_to_127_bytes_and_say_so() {
        let short = PreparedPassword::new(b"userpw");
        assert_eq!(short.as_bytes(), b"userpw");
        assert!(!short.was_truncated());

        let long = vec![b'x'; 200];
        let p = PreparedPassword::new(&long);
        assert_eq!(p.as_bytes().len(), MAX_PASSWORD_LEN);
        assert!(p.was_truncated());

        // Exactly 127 is not truncated; 128 is.
        assert!(!PreparedPassword::new(&[b'x'; 127]).was_truncated());
        assert!(PreparedPassword::new(&[b'x'; 128]).was_truncated());

        // Two passwords sharing their first 127 bytes are the same password.
        let a = PreparedPassword::new(&[vec![b'a'; 127], vec![b'1']].concat());
        let b = PreparedPassword::new(&[vec![b'a'; 127], vec![b'2']].concat());
        assert_eq!(a.as_bytes(), b.as_bytes());
    }

    /// The SASLprep report: ASCII graphic passwords are exact, anything with a
    /// non-ASCII byte or an ASCII control is flagged.
    #[test]
    fn saslprep_relevance_is_reported_for_non_ascii_only() {
        for exact in [
            &b"userpw"[..],
            b"",
            b"a very long ASCII passphrase with spaces",
            b"!@#$%^&*()_+-={}|[]\\:\";'<>?,./",
        ] {
            assert!(
                !PreparedPassword::new(exact).needs_saslprep(),
                "SASLprep is the identity on ASCII graphics: {exact:?}"
            );
        }
        for inexact in [
            "pässwörd".as_bytes(),
            "パスワード".as_bytes(),
            // U+00A0 NO-BREAK SPACE: SASLprep MAPS this to an ordinary space,
            // so a document whose password contains one genuinely cannot be
            // opened without step 1.
            "a\u{00A0}b".as_bytes(),
            &[b'a', 0x01, b'b'],
            // Not valid UTF-8 at all. Still flagged, because step 2 has no
            // defined behaviour for it either.
            &[0xFF, 0xFE],
        ] {
            assert!(
                PreparedPassword::new(inexact).needs_saslprep(),
                "must be flagged: {inexact:?}"
            );
        }
    }
