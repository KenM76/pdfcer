/// Save incrementally and return the whole output file.
fn saved(s: &mut EditSession) -> Vec<u8> {
    s.to_incremental_bytes(&SaveOptions::identity())
        .expect("incremental save")
        .0
}

/// The body of indirect object `id` **as it appears in the saved bytes**.
///
/// Takes the LAST occurrence, because an incremental update appends a new
/// definition after the original and the newest one is what a reader
/// resolves. Deliberately a byte scan rather than a parse: this helper must
/// not be able to repair, normalise, or reinterpret anything on the way
/// in — that is the whole point of asserting here rather than on a model
/// (R159).
fn object_body(pdf: &[u8], id: u32) -> Vec<u8> {
    let needle = format!("\n{id} 0 obj");
    let start = pdf
        .windows(needle.len())
        .enumerate()
        .filter(|(_, w)| *w == needle.as_bytes())
        .map(|(i, _)| i + needle.len())
        .next_back()
        .unwrap_or_else(|| panic!("object {id} is not in the saved file"));
    let end = pdf
        .windows(6)
        .enumerate()
        .skip(start)
        .find(|(_, w)| *w == b"endobj")
        .map(|(i, _)| i)
        .unwrap_or_else(|| panic!("object {id} has no endobj"));
    pdf.get(start..end).unwrap_or_default().to_vec()
}

/// The raw stream payload inside an object body — between the EOL that
/// follows the `stream` keyword and the `endstream` that closes it
/// (§7.3.8.1).
fn stream_payload(body: &[u8]) -> Vec<u8> {
    let kw = b"stream";
    let at = body
        .windows(kw.len())
        .enumerate()
        .find(|(_, w)| *w == kw)
        .map(|(i, _)| i + kw.len())
        .expect("the object has a stream keyword");
    // "shall be followed by CRLF or LF alone, and NOT by CR alone".
    let start = if body.get(at) == Some(&b'\r') {
        at + 2
    } else {
        at + 1
    };
    let end = body
        .windows(9)
        .enumerate()
        .filter(|(_, w)| *w == b"endstream")
        .map(|(i, _)| i)
        .next_back()
        .expect("the object has an endstream");
    // There should be an EOL before `endstream` and it is not part of the
    // data, so trim exactly one.
    let mut stop = end;
    if body.get(stop.wrapping_sub(1)) == Some(&b'\n') {
        stop -= 1;
    }
    if body.get(stop.wrapping_sub(1)) == Some(&b'\r') {
        stop -= 1;
    }
    body.get(start..stop).unwrap_or_default().to_vec()
}

fn contains(hay: &[u8], needle: &[u8]) -> bool {
    hay.windows(needle.len()).any(|w| w == needle)
}

/// A one-page document at an arbitrary declared version, with a real
/// §7.5.4 cross-reference table.
///
/// Written byte by byte with computed offsets rather than by any PDF
/// library — the same discipline the fixture generators follow, so the file
/// cannot inherit a normalization from the code under test. Offsets are
/// derived from the emitted bytes, so the table is correct by construction
/// rather than by a hand count that rots when a byte changes.
fn minimal_pdf(version: &str) -> Vec<u8> {
    let bodies = [
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 200 200] /Resources << >> >>",
    ];
    let mut out = format!("%PDF-{version}\n%\u{e2}\u{e3}\u{cf}\u{d3}\n").into_bytes();
    let mut offsets = Vec::new();
    for (i, body) in bodies.iter().enumerate() {
        offsets.push(out.len());
        out.extend_from_slice(format!("{} 0 obj\n{body}\nendobj\n", i + 1).as_bytes());
    }
    let startxref = out.len();
    out.extend_from_slice(b"xref\n0 4\n0000000000 65535 f \n");
    for off in &offsets {
        out.extend_from_slice(format!("{off:010} 00000 n \n").as_bytes());
    }
    out.extend_from_slice(b"trailer\n<< /Size 4 /Root 1 0 R >>\nstartxref\n");
    out.extend_from_slice(format!("{startxref}\n%%EOF\n").as_bytes());
    out
}

/// The image XObject dictionary as the RELOADED document sees it — the
/// other half of the R159 pairing: the bytes say one thing, and a fresh
/// parse of those bytes must agree.
fn reloaded_image(pdf: &[u8], id: ObjId) -> (Document, Dict, Vec<u8>) {
    let doc = Document::from_bytes(pdf.to_vec()).expect("the saved file reloads");
    let (dict, raw) = {
        let obj = doc.get(id).expect("the image object survives a reload");
        let Object::Stream(stream) = &obj.value else {
            panic!("the image object is not a stream");
        };
        let raw = doc
            .view()
            .slice(stream.data_span)
            .expect("the stream's bytes are addressable")
            .to_vec();
        (stream.dict.clone(), raw)
    };
    (doc, dict, raw)
}

fn dict_int(d: &Dict, key: &[u8]) -> Option<i64> {
    d.get(key).and_then(Object::as_int)
}

fn dict_name(d: &Dict, key: &[u8]) -> Option<Vec<u8>> {
    d.get(key)
        .and_then(Object::as_name)
        .map(|n| n.as_bytes().to_vec())
}

/// The `/XObject` subdictionary the page's resources end up with.
fn page_xobjects(s: &EditSession, page_index: usize) -> Dict {
    let graph = s.graph();
    let page = s.pages().expect("pages")[page_index].id;
    let dict = graph.resolved(page).as_dict().expect("page dict").clone();
    let res = graph
        .resolve(dict.get(b"Resources").expect("page has /Resources"))
        .as_dict()
        .expect("/Resources is a dictionary")
        .clone();
    graph
        .resolve(res.get(b"XObject").expect("/Resources has /XObject"))
        .as_dict()
        .expect("/XObject is a dictionary")
        .clone()
}

