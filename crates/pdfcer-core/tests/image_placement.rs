/// `Contain` — the default — preserves the aspect ratio and centres, and
/// says so.
#[test]
fn contain_preserves_the_aspect_ratio_and_centres() {
    let img = imported("rgb8.png"); // 6 × 4, aspect 1.5
    let mut s = session();
    // A 300 × 100 box: height is the binding constraint, so the image is
    // 150 × 100 and gets 75 points of slack on each side.
    let out = s
        .add_image(&NewImage::new(0, rect(0.0, 0.0, 300.0, 100.0), &img))
        .unwrap();
    let p = out.placed_rect;
    assert!((p.llx - 75.0).abs() < 1e-9, "{p:?}");
    assert!((p.urx - 225.0).abs() < 1e-9, "{p:?}");
    assert!((p.lly - 0.0).abs() < 1e-9, "{p:?}");
    assert!((p.ury - 100.0).abs() < 1e-9, "{p:?}");
    assert!(out.disclosures.letterboxed);
    assert!(!out.disclosures.aspect_distorted);

    let pdf = saved(&mut s);
    let content = stream_payload(&object_body(&pdf, out.content_id.num));
    assert!(
        contains(&content, b"150 0 0 100 75 0 cm"),
        "{}",
        String::from_utf8_lossy(&content)
    );
}

