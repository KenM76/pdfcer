/// All four writes land: the resource names the image, the content invokes
/// that name, and the page's ORIGINAL content stream is still listed and
/// still byte-identical.
///
/// The third clause is R46: a feature that adds page content must not
/// rewrite the content that was already there.
#[test]
fn the_image_is_named_invoked_and_the_original_content_is_untouched() {
    let before = std::fs::read(fixture("dimension/plain-base.pdf")).unwrap();
    let img = imported("rgb8.png");
    let mut s = session();
    let out = s
        .add_image(&NewImage::new(0, rect(0.0, 0.0, 60.0, 40.0), &img))
        .unwrap();

    // The name is in the page's effective /Resources /XObject…
    let xobj = page_xobjects(&s, 0);
    assert_eq!(
        xobj.get(out.resource_name.as_slice())
            .and_then(Object::as_reference),
        Some(out.image_id),
        "the resource entry points at the image object"
    );

    let pdf = saved(&mut s);
    // …the content stream invokes exactly that name…
    let content = stream_payload(&object_body(&pdf, out.content_id.num));
    assert!(contains(
        &content,
        &[b"/", out.resource_name.as_slice(), b" Do"].concat()
    ));

    // …the page's /Contents lists BOTH streams, in order…
    let page_body = object_body(&pdf, 3);
    assert!(
        contains(
            &page_body,
            format!("/Contents [4 0 R {} 0 R]", out.content_id.num).as_bytes()
        ),
        "the overlay is APPENDED, so it draws on top of what was there: {}",
        String::from_utf8_lossy(&page_body)
    );

    // …and the original content stream object is byte-identical, because
    // the incremental save never re-emitted it (R46, ARCHITECTURE.md §5).
    assert_eq!(
        pdf.get(..before.len()),
        Some(before.as_slice()),
        "an incremental save appends; it never rewrites the input prefix"
    );
    assert!(
        !contains(pdf.get(before.len()..).unwrap_or_default(), b"\n4 0 obj"),
        "object 4 — the page's original content stream — was not touched, so \
         it must not appear in the update section at all"
    );
}

