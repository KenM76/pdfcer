//! Placing a raster image on a page as an image XObject (§8.9.5).
//!
//! ## What these tests are really checking, and why they read the BYTES
//!
//! An image placement is **four coordinated writes**: the image XObject, an
//! optional `/SMask`, a content stream that invokes it, and one patch to the
//! page dictionary carrying both `/Contents` and `/Resources`. Any three
//! without the fourth produce a document that is broken in a way nothing
//! reports — a page whose resources name an XObject its content never
//! invokes shows nothing at all, and every in-memory assertion about the
//! image still passes.
//!
//! Worse, the load-bearing property of this whole feature is a claim about
//! *bytes*: that a JPEG's codestream reaches the document **unchanged**, and
//! that a PNG's `IDAT` is reused verbatim under `/Predictor 15`. A model
//! that says "the image is there" cannot see a stream that holds the right
//! pixels behind the wrong filter, or the right filter over re-compressed
//! bytes. **R159** names exactly this: *"a defect that lives in the BYTES
//! must be asserted in the BYTES."*
//!
//! So the assertions here mostly run over the SAVED FILE, extracted with a
//! deliberately dumb scanner ([`object_body`], [`stream_payload`]) that does
//! no repair of its own — because a lenient parser is precisely what would
//! hide the failures this feature can have.
//!
//! ## Fixture provenance
//!
//! Every image under `fixtures/synthetic/images/` is generated by
//! `tools/gen-image-fixtures.py` from pixel data this project authored.
//! Nothing is downloaded (project rule 7, `LEGAL.md` §5). See that
//! directory's `PROVENANCE.md`.

