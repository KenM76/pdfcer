// ---------------------------------------------------------------------------
// Harness
// ---------------------------------------------------------------------------

fn fixture(rel: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../fixtures/synthetic")
        .join(rel)
}

fn tiff_bytes(name: &str) -> Vec<u8> {
    std::fs::read(fixture(&format!("tiff/{name}")))
        .unwrap_or_else(|e| panic!("read fixture tiff/{name}: {e}"))
}

fn imported(name: &str) -> ImportedImage {
    image_import::import(&tiff_bytes(name)).unwrap_or_else(|e| panic!("import tiff/{name}: {e}"))
}

/// The decoded sample buffer of an imported TIFF.
///
/// Every TIFF lands on plain `/FlateDecode` (there is no predictor variant
/// to describe a TIFF, and `/DCTDecode` is not reachable from this reader),
/// so one branch is enough — and asserting that is itself worth doing, which
/// the `filter` check here does.
fn samples(img: &ImportedImage) -> Vec<u8> {
    assert_eq!(
        img.filter,
        ImportFilter::Flate,
        "a TIFF always lands on plain /FlateDecode"
    );
    flate::decode(&img.data, None).expect("the stream inflates")
}

fn mask_samples(img: &ImportedImage) -> Vec<u8> {
    let mask = img.soft_mask.as_ref().expect("this image has a soft mask");
    flate::decode(&mask.data, None).expect("the mask inflates")
}

fn session() -> EditSession {
    EditSession::new(Document::load(&fixture("dimension/plain-base.pdf")).expect("load fixture"))
}

fn rect(llx: f64, lly: f64, urx: f64, ury: f64) -> Rect {
    Rect { llx, lly, urx, ury }
}

fn saved(s: &mut EditSession) -> Vec<u8> {
    s.to_incremental_bytes(&SaveOptions::identity())
        .expect("incremental save")
        .0
}

/// The body of indirect object `id` **as it appears in the saved bytes**.
///
/// A byte scan, not a parse: this helper must not be able to repair or
/// reinterpret anything on the way in — that is the point of asserting here
/// rather than on a model (R159). Takes the LAST occurrence, because an
/// incremental update appends a new definition after the original.
fn object_body(pdf: &[u8], id: u32) -> Vec<u8> {
    let needle = format!("\n{id} 0 obj");
    let start = pdf
        .windows(needle.len())
        .enumerate()
        .filter(|(_, w)| *w == needle.as_bytes())
        .map(|(i, _)| i + needle.len())
        .next_back()
        .unwrap_or_else(|| panic!("object {id} is not in the saved file"));
    let end = pdf
        .windows(6)
        .enumerate()
        .skip(start)
        .find(|(_, w)| *w == b"endobj")
        .map(|(i, _)| i)
        .unwrap_or_else(|| panic!("object {id} has no endobj"));
    pdf.get(start..end).unwrap_or_default().to_vec()
}

/// The raw stream payload inside an object body (§7.3.8.1).
fn stream_payload(body: &[u8]) -> Vec<u8> {
    let kw = b"stream";
    let at = body
        .windows(kw.len())
        .enumerate()
        .find(|(_, w)| *w == kw)
        .map(|(i, _)| i + kw.len())
        .expect("the object has a stream keyword");
    let start = if body.get(at) == Some(&b'\r') {
        at + 2
    } else {
        at + 1
    };
    let end = body
        .windows(9)
        .enumerate()
        .filter(|(_, w)| *w == b"endstream")
        .map(|(i, _)| i)
        .next_back()
        .expect("the object has an endstream");
    let mut stop = end;
    if body.get(stop.wrapping_sub(1)) == Some(&b'\n') {
        stop -= 1;
    }
    if body.get(stop.wrapping_sub(1)) == Some(&b'\r') {
        stop -= 1;
    }
    body.get(start..stop).unwrap_or_default().to_vec()
}

fn contains(hay: &[u8], needle: &[u8]) -> bool {
    hay.windows(needle.len()).any(|w| w == needle)
}

/// The authored colour ramp, as `/DeviceRGB` samples — computed here rather
/// than copied from the generator, so the two are independent statements of
/// the same intent.
fn expected_rgb() -> Vec<u8> {
    let (w, h) = (6u32, 4u32);
    let mut out = Vec::new();
    for y in 0..h {
        for x in 0..w {
            let r = (255 * x / (w - 1)) as u8;
            let g = (255 * y / (h - 1)) as u8;
            out.extend_from_slice(&[r, g, 255 - r]);
        }
    }
    out
}

fn expected_gray() -> Vec<u8> {
    let (w, h) = (6u32, 4u32);
    let mut out = Vec::new();
    for y in 0..h {
        for x in 0..w {
            out.push((255 * (x + y) / (w + h - 2)) as u8);
        }
    }
    out
}

/// The authored alpha ramp — deliberately non-binary, which is what makes
/// associated and unassociated alpha distinguishable at all.
fn expected_alpha() -> Vec<u8> {
    let (w, h) = (6u32, 4u32);
    let mut out = Vec::new();
    for y in 0..h {
        for x in 0..w {
            out.push((255 * (x * h + y) / (w * h - 1)) as u8);
        }
    }
    out
}

