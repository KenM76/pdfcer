/// Every TIFF sub-feature pdfcer declines fails with its own key, never a
/// generic "decode failed". A wrong-looking image is the worse outcome, and
/// these are precisely the tag combinations that produce one when guessed at.
#[test]
fn declined_tiff_sub_features_are_refused_by_name() {
    for (name, feature) in [
        ("tiled.tif", "TIFF/tiled"),
        ("planar.tif", "TIFF/planar-separate"),
        ("ccittg4.tif", "TIFF/ccitt-g4"),
        ("float32.tif", "TIFF/sample-format-float"),
    ] {
        let err = image_import::import(&tiff_bytes(name)).unwrap_err();
        assert_eq!(
            err,
            ImageImportError::Unsupported { feature },
            "{name} must be refused by name"
        );
        assert!(
            err.to_string().contains(feature),
            "the message names the feature: {err}"
        );
    }
}

/// BigTIFF is a different parser, not a sub-feature of classic TIFF, so it is
/// refused at the **sniffer** under its own format name — and the message
/// names what does work, which now includes TIFF. Refusing it as "TIFF" would
/// produce a sentence that contradicts itself.
#[test]
fn bigtiff_is_refused_as_its_own_format_and_the_message_names_tiff() {
    let err = image_import::import(&tiff_bytes("bigtiff.tif")).unwrap_err();
    assert_eq!(
        err,
        ImageImportError::UnsupportedFormat { format: "BigTIFF" }
    );
    let msg = err.to_string();
    assert!(msg.contains("BigTIFF"), "{msg}");
    assert!(msg.contains(SUPPORTED_FORMATS), "{msg}");
    assert!(
        SUPPORTED_FORMATS.contains("TIFF"),
        "the supported-format sentence must now include TIFF"
    );
}

/// The sniffer recognises classic TIFF in both byte orders and routes it to
/// the reader rather than to a refusal.
#[test]
fn the_sniffer_routes_classic_tiff_to_the_reader() {
    for name in ["gray8-be.tif", "gray8-le.tif"] {
        assert_eq!(
            image_import::sniff(&tiff_bytes(name)).unwrap(),
            ImageFormat::Tiff,
            "{name}"
        );
    }
    assert_eq!(ImageFormat::Tiff.name(), "TIFF");
}

/// Truncation must be a diagnosis, never a panic: `pdfcer-core` denies
/// unchecked indexing crate-wide precisely because this input is untrusted.
/// Run over every fixture, including the refusals, because a refusal path
/// that panics on a short file is still a denial-of-service bug.
#[test]
fn every_truncation_of_every_fixture_is_diagnosed_not_panicked() {
    for name in [
        "rgb8-lzw.tif",
        "rgb8-packbits.tif",
        "rgba8-associated.tif",
        "multipage.tif",
        "pal8.tif",
        "tiled.tif",
    ] {
        let bytes = tiff_bytes(name);
        for cut in 0..bytes.len() {
            // The result is irrelevant; not unwinding is the assertion.
            let _ = image_import::import(bytes.get(..cut).unwrap());
        }
    }
}
