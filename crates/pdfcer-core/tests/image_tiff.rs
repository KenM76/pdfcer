/// Every fixture declares 300 dpi in inches, and none of them is placed at
/// that size unless asked — the resolution is REPORTED, never applied
/// silently (rule 4; see `ImportedImage::natural_size_pt`).
#[test]
fn a_declared_resolution_is_reported_and_not_applied() {
    let img = imported("rgb8-none.tif");
    let (dx, dy) = img.dpi.expect("the fixtures declare 300 dpi");
    assert!((dx - 300.0).abs() < 0.5, "{dx}");
    assert!((dy - 300.0).abs() < 0.5, "{dy}");
    assert_eq!(img.orientation, Orientation::Identity);

    // Natural size at 300 dpi: 6 px = 1.44 pt, 4 px = 0.96 pt.
    let (w, h) = img.natural_size_pt();
    assert!((w - 1.44).abs() < 1e-6, "{w}");
    assert!((h - 0.96).abs() < 1e-6, "{h}");

    // …but the placement uses the caller's rectangle, not that.
    let mut s = session();
    let out = s
        .add_image(&NewImage::new(0, rect(0.0, 0.0, 120.0, 80.0), &img))
        .expect("place the TIFF");
    assert!((out.placed_rect.urx - out.placed_rect.llx - 120.0).abs() < 1e-6);
}

