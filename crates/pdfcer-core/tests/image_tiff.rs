/// `PhotometricInterpretation 0` means **0 is white** — the reverse of
/// `/DeviceGray` (§8.6.4.2). Read without the complement, a bilevel scan
/// imports as a photographic negative, which is how monochrome CAD output
/// and every fax-lineage scan would look.
#[test]
fn a_white_is_zero_bilevel_scan_lands_in_devicegray_polarity() {
    let img = imported("bilevel-whiteiszero.tif");
    assert_eq!(img.bits_per_component, 1);
    assert_eq!(img.color_space, ImportColorSpace::DeviceGray);
    assert!(img.notes.tiff_white_is_zero_inverted);

    // The generator writes bit 1 where (x + y) % 3 == 0, and 1 means WHITE
    // in a WhiteIsZero-complemented world... which is to say: the stored bit
    // was 1 = "not zero" = black-ish in TIFF terms, and after the complement
    // it must read 0 in PDF terms.
    let got = samples(&img);
    assert_eq!(got.len(), 4, "one byte per row at 6 bits + padding");
    for (y, byte) in got.iter().enumerate() {
        for x in 0..6usize {
            let stored = u8::from((x + y) % 3 == 0);
            let bit = (byte >> (7 - x)) & 1;
            assert_eq!(
                bit,
                1 - stored,
                "sample ({x}, {y}) must be the complement of what was stored"
            );
        }
    }
}

/// TIFF 6.0 §16 stores a `ColorMap` as three consecutive **blocks** (all
/// red, then all green, then all blue) while §8.6.6.3 wants interleaved
/// triples. A reader that copies the field straight through gets a palette
/// whose every colour is wrong.
#[test]
fn a_colormap_is_deblocked_into_an_indexed_lookup() {
    let img = imported("pal8.tif");
    let ImportColorSpace::Indexed { hival, lookup } = &img.color_space else {
        panic!("a palette TIFF must become /Indexed: {:?}", img.color_space);
    };
    assert_eq!(*hival, 255, "2^8 entries, so hival is 255");
    assert_eq!(lookup.len(), 256 * 3);
    assert_eq!(
        lookup.get(0..18).unwrap(),
        &[
            0, 0, 0, // 0 black
            255, 0, 0, // 1 red
            0, 255, 0, // 2 green
            0, 0, 255, // 3 blue
            255, 255, 0, // 4 yellow
            255, 255, 255, // 5 white
        ],
        "the three ColorMap blocks must interleave into RGB triples"
    );
    assert!(!img.notes.tiff_palette_assumed_8bit);

    let indices: Vec<u8> = (0..4u8)
        .flat_map(|y| (0..6u8).map(move |x| (x + 2 * y) % 6))
        .collect();
    assert_eq!(samples(&img), indices);
}

/// The recorded standard-vs-practice divergence: a `ColorMap` whose 16-bit
/// fields all hold 0–255 was written 8-bit, and trusting TIFF 6.0 §16
/// literally renders it almost entirely black. pdfcer applies libtiff's
/// heuristic **and discloses that it fired** — the two fixtures together
/// prove the heuristic fires when it should and not when it should not.
#[test]
fn an_eight_bit_colormap_is_detected_disclosed_and_matches_the_16_bit_one() {
    let spec = imported("pal8.tif");
    let real = imported("pal8-8bit-colormap.tif");
    assert!(!spec.notes.tiff_palette_assumed_8bit);
    assert!(
        real.notes.tiff_palette_assumed_8bit,
        "the heuristic fired and must say so (rule 4)"
    );
    assert_eq!(
        spec.color_space, real.color_space,
        "both spellings of the same palette must produce the same lookup"
    );
}

