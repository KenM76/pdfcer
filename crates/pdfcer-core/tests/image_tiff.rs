/// Every compression pdfcer accepts must decode to the **same** samples.
///
/// One table rather than five tests, because the property under test is
/// exactly that they agree: a per-compression test could pass with five
/// different pictures.
#[test]
fn every_accepted_compression_decodes_to_the_same_picture() {
    let want = expected_rgb();
    for name in [
        "rgb8-none.tif",
        "rgb8-lzw.tif",
        "rgb8-deflate.tif",
        "rgb8-deflate-strips.tif",
        "rgb8-packbits.tif",
    ] {
        let img = imported(name);
        assert_eq!(img.format, ImageFormat::Tiff);
        assert_eq!(img.color_space, ImportColorSpace::DeviceRgb);
        assert_eq!(img.bits_per_component, 8);
        assert_eq!(samples(&img), want, "{name}");
    }
}

/// `rgb8-lzw.tif` is LZW **plus `Predictor 2` plus three strips** — the
/// shape a real tool writes, and three independent things to get wrong at
/// once. Called out separately from the table above so a failure names which
/// property broke.
#[test]
fn lzw_with_horizontal_differencing_across_strips_reassembles() {
    let img = imported("rgb8-lzw.tif");
    assert_eq!(samples(&img), expected_rgb());
    assert_eq!(
        img.notes.recompressed,
        Some(RecompressReason::SourceCodecNotReusable),
        "pdfcer writes no LZW encoder (R28), so nothing can be passed through"
    );
}

/// **The PackBits divergence.** TIFF 6.0 §9 makes `0x80` a *no-op*;
/// ISO 32000-1 §7.4.5 makes `128` *end-of-data*. `rgb8-packbits.tif` carries
/// one deliberately, mid-strip. A TIFF reader that called pdfcer's own
/// `RunLengthDecode` filter would stop there and lose the rest of the image.
#[test]
fn a_packbits_strip_survives_its_embedded_0x80_no_op() {
    let img = imported("rgb8-packbits.tif");
    let got = samples(&img);
    assert_eq!(
        got.len(),
        6 * 4 * 3,
        "the whole image, not just the bytes before the 0x80"
    );
    assert_eq!(got, expected_rgb());
}

// ---------------------------------------------------------------------------
// Passthrough — the bytes assertion (R159)
// ---------------------------------------------------------------------------

/// A single-strip, `Predictor 1`, Deflate TIFF's strip payload **is** a
/// conforming plain `/FlateDecode` stream, and reaches the document byte for
/// byte.
///
/// Asserted over the SAVED FILE rather than over the in-memory image: a
/// re-deflate would produce a working document with a correct-looking
/// picture and slightly different bytes, which only a byte comparison
/// catches.
#[test]
fn a_single_strip_deflate_tiff_reaches_the_document_byte_identical() {
    let img = imported("rgb8-deflate.tif");
    assert!(
        img.notes.recompressed.is_none(),
        "nothing had to be transformed, so nothing had to be re-compressed"
    );

    let mut s = session();
    let out = s
        .add_image(&NewImage::new(0, rect(20.0, 20.0, 140.0, 100.0), &img))
        .expect("place the TIFF");
    let pdf = saved(&mut s);

    let body = object_body(&pdf, out.image_id.num);
    assert_eq!(
        stream_payload(&body),
        img.data,
        "the /FlateDecode stream IS the TIFF's own strip"
    );
    assert!(contains(&body, b"/Filter /FlateDecode"), "{body:?}");
    assert!(
        !contains(&body, b"/DecodeParms"),
        "a plain Flate stream carries no predictor parameters: {body:?}"
    );
    assert!(contains(&body, b"/Width 6"));
    assert!(contains(&body, b"/Height 4"));
    assert!(contains(&body, b"/ColorSpace /DeviceRGB"));
    assert!(contains(&body, b"/BitsPerComponent 8"));
}

/// …and the same picture in **three** strips must NOT be passed through:
/// three concatenated zlib streams are not one zlib stream. Paired with the
/// test above so the gate is exercised in both directions — a gate that only
/// ever says "yes" is not a gate.
#[test]
fn a_multi_strip_deflate_tiff_is_rebuilt_not_passed_through() {
    let one = imported("rgb8-deflate.tif");
    let many = imported("rgb8-deflate-strips.tif");
    assert_eq!(samples(&one), samples(&many), "the same picture");
    assert_eq!(
        many.notes.recompressed,
        Some(RecompressReason::SourceCodecNotReusable)
    );
    assert_eq!(
        many.notes.recompressed.map(RecompressReason::key),
        Some("source-codec-not-reusable"),
        "the stable key a front end reports"
    );
}

