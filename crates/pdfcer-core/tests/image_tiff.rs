//! Importing a TIFF and placing it on a page (TIFF 6.0 → §8.9.5 image XObject).
//!
//! ## Why this is a separate integration test from `image_placement.rs`
//!
//! That file proves the **placement machinery** — four coordinated writes,
//! the page patch, the fitting arithmetic — using PNG/JPEG/BMP sources. This
//! one proves the **container reader**, and TIFF's failure modes are a
//! different shape from the other three formats':
//!
//! - PNG has one layout and JPEG has one codestream. A TIFF is a *directory
//!   of tags*, and the same picture is legally storable in dozens of ways.
//!   Nothing in the file is redundant enough to catch a misread, so a wrong
//!   `PlanarConfiguration`, a missed byte swap or an unhandled predictor
//!   produces a **plausible-looking, entirely wrong picture** rather than an
//!   error anywhere.
//! - The load-bearing assertions are therefore mostly **"these two files must
//!   import to identical samples"** pairs: the same picture in `II` and `MM`,
//!   the same picture under five compressions, the same picture with straight
//!   and premultiplied alpha. A single-file assertion cannot distinguish "the
//!   decoder is right" from "the decoder and the fixture generator are wrong
//!   in the same direction"; a pair can.
//!
//! Where a claim is about **bytes** — that a single-strip Deflate TIFF's own
//! strip payload reaches the document unchanged — the assertion runs over the
//! SAVED FILE, extracted with a deliberately dumb byte scanner, per **R159**:
//! *"a defect that lives in the BYTES must be asserted in the BYTES."*
//!
//! ## Fixture provenance
//!
//! Every file under `fixtures/synthetic/tiff/` is generated by
//! `fixtures/synthetic/tiff/gen-tiff-fixtures.py` from pixel data this
//! project authored. Nothing is downloaded (project rule 7, `LEGAL.md` §5).
//! See that directory's `PROVENANCE.md` — including why the generator sits
//! beside its output rather than in `tools/`.

