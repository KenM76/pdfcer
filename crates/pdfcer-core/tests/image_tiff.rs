/// Straight (`unassociated`) alpha splits directly into a `/DeviceRGB` base
/// and an 8-bit `/SMask` — and the placement writes the mask as its own
/// object, referenced by `/SMask`.
#[test]
fn unassociated_alpha_becomes_a_soft_mask() {
    let img = imported("rgba8-unassociated.tif");
    assert_eq!(img.color_space, ImportColorSpace::DeviceRgb);
    assert_eq!(samples(&img), expected_rgb());
    assert_eq!(mask_samples(&img), expected_alpha());
    assert!(img.notes.alpha_to_soft_mask);
    assert!(!img.notes.tiff_associated_alpha_unpremultiplied);
    assert_eq!(img.notes.recompressed, Some(RecompressReason::AlphaSplit));

    let mut s = session();
    let out = s
        .add_image(&NewImage::new(0, rect(0.0, 0.0, 120.0, 80.0), &img))
        .expect("place the RGBA TIFF");
    let mask_id = out.soft_mask_id.expect("a soft-mask object was written");
    let pdf = saved(&mut s);

    let body = object_body(&pdf, out.image_id.num);
    assert!(
        contains(&body, format!("/SMask {} 0 R", mask_id.num).as_bytes()),
        "the base image must reference its mask: {body:?}"
    );
    let mask_body = object_body(&pdf, mask_id.num);
    assert!(contains(&mask_body, b"/ColorSpace /DeviceGray"));
    assert!(contains(&mask_body, b"/Width 6"));
    assert!(contains(&mask_body, b"/Height 4"));
    assert_eq!(
        flate::decode(&stream_payload(&mask_body), None).unwrap(),
        expected_alpha()
    );
}

/// **The compositing trap.** `ExtraSamples 1` means the colour samples are
/// PREMULTIPLIED by alpha; a `/SMask` is a straight alpha channel. Stored
/// as-is, every partly-transparent pixel composites double-dark — the more
/// transparent, the darker — which reads as "pdfcer lost the transparency"
/// rather than as an inverted convention.
///
/// The two fixtures carry the **same picture**, so the assertion is that
/// they agree, not merely that something happened. They cannot agree
/// exactly: premultiplication quantises, and nothing can put back what it
/// discarded. The tolerance is the honest statement of that, and it is
/// checked to be *tight where it can be* — at full opacity the recovery is
/// exact.
#[test]
fn associated_alpha_is_unpremultiplied_back_to_the_straight_picture() {
    let straight = imported("rgba8-unassociated.tif");
    let premultiplied = imported("rgba8-associated.tif");

    assert!(premultiplied.notes.tiff_associated_alpha_unpremultiplied);
    assert!(!straight.notes.tiff_associated_alpha_unpremultiplied);
    assert_eq!(
        mask_samples(&premultiplied),
        mask_samples(&straight),
        "the alpha channel itself is untouched by either convention"
    );

    let want = samples(&straight);
    let got = samples(&premultiplied);
    let alpha = expected_alpha();
    assert_eq!(got.len(), want.len());

    let mut exact_at_full_alpha = 0usize;
    for (i, (g, w)) in got.iter().zip(want.iter()).enumerate() {
        let a = alpha.get(i / 3).copied().unwrap_or(0);
        if a == 0 {
            // A fully transparent pixel's premultiplied colour is all-zero
            // and carries NO information; any value is equally right.
            continue;
        }
        // The reconstruction error is bounded by the quantisation the
        // premultiply performed: about one output step per unit of alpha.
        let tolerance = (255 / u32::from(a).max(1)) as u8 + 1;
        assert!(
            g.abs_diff(*w) <= tolerance,
            "sample {i} (alpha {a}): recovered {g}, want {w}, tolerance {tolerance}"
        );
        if a == 255 {
            assert_eq!(g, w, "at full opacity the recovery is EXACT");
            exact_at_full_alpha += 1;
        }
    }
    assert!(
        exact_at_full_alpha > 0,
        "the fixture must contain at least one fully-opaque pixel, or the \
         exactness claim above is never tested"
    );
}

/// `ExtraSamples 0` — and an omitted tag — is *"unspecified data"*, not
/// opacity. Reading it as alpha is how an otherwise-perfect image renders
/// entirely invisible; the channel is dropped and the drop is disclosed.
#[test]
fn unspecified_extra_samples_are_dropped_not_read_as_opacity() {
    let img = imported("rgba8-unspecified.tif");
    assert!(
        img.soft_mask.is_none(),
        "a channel of undeclared meaning is not an alpha channel"
    );
    assert_eq!(samples(&img), expected_rgb());
    assert_eq!(img.notes.tiff_extra_samples_dropped, 1);
    assert!(!img.notes.alpha_to_soft_mask);
}

