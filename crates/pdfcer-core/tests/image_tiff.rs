// Byte order — the single most common TIFF bug
// ---------------------------------------------------------------------------

/// The same picture stored `II` and `MM` must import to identical samples.
///
/// This pair catches a reader that ignores the byte-order mark entirely; it
/// does **not** catch one that reads the tags correctly and the sample data
/// incorrectly, which is what the 16-bit pair below is for.
#[test]
fn both_byte_orders_of_the_same_8_bit_image_agree() {
    let be = imported("gray8-be.tif");
    let le = imported("gray8-le.tif");
    assert_eq!(be.color_space, ImportColorSpace::DeviceGray);
    assert_eq!((be.width, be.height), (6, 4));
    assert_eq!(samples(&be), expected_gray());
    assert_eq!(
        samples(&be),
        samples(&le),
        "II and MM are the same picture and must decode identically"
    );
}

/// **The endianness assertion that matters.** TIFF stores 16-bit *sample
/// data* in the file's byte order; ISO 32000-1 §8.9.3 requires PDF samples
/// high-order byte first. So an `II` file's pixels must be byte-swapped, and
/// a reader that swaps the tags but not the samples passes the 8-bit pair
/// above and fails here — producing an image whose every channel is
/// scrambled into noise that still has the right dimensions.
#[test]
fn sixteen_bit_samples_are_big_endian_whatever_the_file_said() {
    let be = imported("gray16-be.tif");
    let le = imported("gray16-le.tif");
    assert_eq!(be.bits_per_component, 16);
    assert_eq!(le.bits_per_component, 16);

    let expected: Vec<u8> = expected_gray()
        .into_iter()
        .flat_map(|v| (u16::from(v) * 257).to_be_bytes())
        .collect();
    assert_eq!(samples(&be), expected);
    assert_eq!(
        samples(&le),
        expected,
        "an II file's 16-bit samples must be swapped into PDF's byte order"
    );
}

