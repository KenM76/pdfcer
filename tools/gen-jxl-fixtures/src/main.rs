//! Writes `crates/pdfcer-image-codec/src/fixtures_jxl.rs`: synthetic JPEG XL
//! fixtures encoded by `zune-jpegxl` (lossless, a different implementation
//! from the `jxl-oxide` decoder under test). Run from the repo root:
//! `cargo run --manifest-path tools/gen-jxl-fixtures/Cargo.toml`.
//! Standalone, not a workspace member, so the encoder never enters a build.

use std::fmt::Write as _;

use zune_core::bit_depth::BitDepth;
use zune_core::colorspace::ColorSpace;
use zune_core::options::EncoderOptions;
use zune_jpegxl::JxlSimpleEncoder;

fn encode(w: usize, h: usize, cs: ColorSpace, px: &[u8]) -> Vec<u8> {
    let mut out = Vec::new();
    JxlSimpleEncoder::new(px, EncoderOptions::new(w, h, cs, BitDepth::Eight))
        .encode(&mut out)
        .expect("encode");
    out
}

/// ISO/IEC 18181-2 container: signature box, `ftyp`, one `jxlc` box.
fn contain(codestream: &[u8]) -> Vec<u8> {
    let mut out = vec![
        0, 0, 0, 0x0C, b'J', b'X', b'L', b' ', 0x0D, 0x0A, 0x87, 0x0A,
    ];
    out.extend_from_slice(&[0, 0, 0, 0x14]);
    out.extend_from_slice(b"ftypjxl \0\0\0\0jxl ");
    out.extend_from_slice(&u32::try_from(codestream.len() + 8).unwrap().to_be_bytes());
    out.extend_from_slice(b"jxlc");
    out.extend_from_slice(codestream);
    out
}

fn array(out: &mut String, doc: &str, name: &str, bytes: &[u8]) {
    writeln!(out, "/// {doc}\npub const {name}: &[u8] = &[").unwrap();
    for row in bytes.chunks(12) {
        let cells: Vec<String> = row.iter().map(|b| format!("0x{b:02X}")).collect();
        writeln!(out, "    {},", cells.join(", ")).unwrap();
    }
    writeln!(out, "];\n").unwrap();
}

fn main() {
    let gray = [0, 85, 170, 255, 255, 170, 85, 0];
    let rgb = [255, 0, 0, 0, 255, 0, 0, 0, 255, 255, 255, 255];
    let rgba = [
        255, 0, 0, 255, 0, 0, 255, 64, 128, 128, 128, 128, 0, 0, 0, 0,
    ];
    let gray_cs = encode(4, 2, ColorSpace::Luma, &gray);
    let mut s = String::from(
        "//! Synthetic JPEG XL fixtures for the `JXLDecode` adapter's tests.\n\
         //!\n\
         //! GENERATED by `tools/gen-jxl-fixtures` from pixel patterns authored for\n\
         //! this project (`docs/LEGAL.md` §5); do not hand-edit.\n\n",
    );
    array(
        &mut s,
        "4x2 gray ramp, bare codestream.",
        "JXL_GRAY_4X2",
        &gray_cs,
    );
    array(
        &mut s,
        "The same codestream in an ISO/IEC 18181-2 container.",
        "JXL_GRAY_4X2_BOXED",
        &contain(&gray_cs),
    );
    array(
        &mut s,
        "Source pixels of the gray fixtures.",
        "JXL_GRAY_4X2_SAMPLES",
        &gray,
    );
    array(
        &mut s,
        "2x2 RGB: red, green / blue, white.",
        "JXL_RGB_2X2",
        &encode(2, 2, ColorSpace::RGB, &rgb),
    );
    array(
        &mut s,
        "Source pixels of `JXL_RGB_2X2`.",
        "JXL_RGB_2X2_SAMPLES",
        &rgb,
    );
    array(
        &mut s,
        "2x2 RGBA, straight alpha 255/64/128/0.",
        "JXL_RGBA_2X2",
        &encode(2, 2, ColorSpace::RGBA, &rgba),
    );
    array(
        &mut s,
        "Source pixels of `JXL_RGBA_2X2`, interleaved RGBA.",
        "JXL_RGBA_2X2_SAMPLES",
        &rgba,
    );
    std::fs::write("crates/pdfcer-image-codec/src/fixtures_jxl.rs", s).expect("write");
}
