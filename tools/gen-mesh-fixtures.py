#!/usr/bin/env python3
"""Regenerate fixtures/synthetic/mesh/ - shading types 4, 5, 6 and 7.

WHY THIS EXISTS
---------------
`Pass 125.0` decodes and rasterises the four **mesh** shading types
(ISO 32000-1 8.7.4.5.5-.8). The only mesh shadings this project has access
to are **two type 7 patches in one licensed print-conformance patch**, which
is not redistributable (`docs/LEGAL.md` §5) and covers exactly one of the
four types, one edge-flag value, one bit-width combination, and neither the
`/Function` form nor any refusal path.

So without these fixtures the Pass would ship with `cargo test` proving the
arithmetic in `mesh.rs`'s unit tests and **nothing proving the arithmetic is
wired to a content stream** for three of the four types. That is the gap
`tools/gen-nonisolated-group-fixtures.py`'s header names for its own Pass,
and it is the same gap here.

THE ORACLE PROBLEM, AND HOW THESE FIXTURES SOLVE IT WITHOUT A REFERENCE
----------------------------------------------------------------------
A rendered gradient has no obvious right answer to assert against, and a
screenshot committed as "known good" only pins whatever the code did on the
day it was taken. These fixtures avoid that by being built in **equivalence
pairs**: two files that the STANDARD says must render identically, by
different code paths. A pair disagreeing is a defect no matter which of the
two is wrong, and neither file has to be blessed by anybody.

| pair | why they must agree | which clause |
|---|---|---|
| `type6_coons.pdf` / `type7_tensor.pdf` | a Coons patch IS a tensor patch whose four internal points are derived from its boundary; the type 7 file carries those four points EXPLICITLY, computed here by the spec's own equations | 8.7.4.5.8, `MSH30` |
| `type4_triangles.pdf` / `type5_lattice.pdf` | the type 4 edge-flag sequence `0,0,0,1` produces exactly the triangle pair a 2x2 type 5 lattice produces | `MSH16`-`MSH19` vs `MSH22` |

Everything else is asserted against a value that is fixed by arithmetic
rather than by taste: a corner pixel must be the corner colour, because
every one of these surfaces interpolates its corners exactly.

THE FILES
---------
| file | what it is | what only it can catch |
|---|---|---|
| `type4_triangles.pdf` | two triangles, edge flags `0,0,0,1` | the flag state machine's relabelling |
| `type5_lattice.pdf` | a 2x2 lattice, no flag field at all | a parser that leaves `BitsPerFlag` in the record |
| `type6_coons.pdf` | one Coons patch, 12 control points | the boundary-curve order, and the corner-colour walk |
| `type7_tensor.pdf` | the same patch as 16 explicit points | the internal-point cycle `p11 p12 p22 p21` |
| `type6_flag1.pdf` | two patches, the second continuing on edge 1 | the inheritance table's flag-1 row: the new `u=0` edge is the previous patch's `v=1` row, NOT reversed |
| `type6_flag2.pdf` | the same, on edge 2 | flag 2 inherits the previous patch's `u=1` column **reversed** |
| `type6_flag3.pdf` | the same, on edge 3 | flag 3 inherits the previous patch's `v=0` row **reversed** |
| `type7_flag1.pdf` | a type 7 continued patch | that a continued type 7 record is **12** coordinate pairs, not 8 - the four internal points are never inherited |
| `type4_parametric.pdf` | type 4 with a NON-LINEAR `/Function` | `f(lerp(t))` versus `lerp(f(t))` - see below |
| `type6_unaligned.pdf` | `BitsPerFlag 4`, `BitsPerCoordinate 12`, `BitsPerComponent 4` | the `MSH-A1` patch-padding ambiguity, which is unobservable on any byte-aligned file |
| `type4_truncated.pdf` | a stream cut part-way through its fourth vertex | that the complete records still paint and the tail is DISCLOSED |
| `type4_indexed.pdf` | an `Indexed` colour space | the `MSH-A4` refusal, which must be a named refusal and not a palette-order rainbow |
| `type6_pattern.pdf` | the same Coons patch reached as a `PatternType 2` FILL rather than by `sh` | the OTHER paint route. The two anchor in opposite coordinate spaces - `sh` in current user space, a pattern in the page's INITIAL space - and a mesh is forward-rasterised, so it inverts the transform the analytic path uses directly. A sign or an inversion dropped there renders a mesh in the wrong place, at the wrong size, or not at all |

★ `type4_parametric.pdf` USES AN EXPONENT OF 2 ON PURPOSE. With a linear
`/Function` (`/N 1`) the two orders of operations agree exactly - `f` is
affine, so `f(lerp(t)) == lerp(f(t))` - and the fixture would pass under the
wrong implementation. `/N 2` makes them differ at every interior point, and
the midpoint of the ramp is where they differ most.

SOURCE MATERIAL AND LICENCE (LEGAL.md §5, project rule 7)
---------------------------------------------------------
**Nothing here derives from a third-party file.** These are `LEGAL.md` §5
category (a): wholly synthetic, authored for this project, generated by this
committed script from geometry and colours this project chose. Nothing was
downloaded from anywhere, and in particular **no byte of any licensed
conformance suite is reproduced or paraphrased here** - the type 7 file is
built from the standard's own equations, not from any sample.

The PDFs are assembled byte by byte with a classic §7.5.4 cross-reference
table, no object streams and no compression, so a failing test can be read
in a hex editor and a fuzzer mutating one keeps producing something the
parser will engage with.

HOW TO REGENERATE
-----------------
    python tools/gen-mesh-fixtures.py
"""

from __future__ import annotations

from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "fixtures" / "synthetic" / "mesh"

# The page, and the square every mesh covers inside it. Kept well away from
# the page edge so that the CRACK_MARGIN_PX fringe on the mesh silhouette
# cannot run off the pixmap and turn a coverage question into a clipping
# question.
PAGE = 120
LO, HI = 10.0, 110.0

# Corner colours, in walk-around order p00, p03, p33, p30 - i.e.
# (u,v) = (0,0), (0,1), (1,1), (1,0). MSH24. Deliberately four saturated
# primaries so that a transposed assignment shows as a completely different
# picture rather than as a subtle shift.
C00 = (1.0, 0.0, 0.0)  # red     at (LO, LO)
C03 = (0.0, 1.0, 0.0)  # green   at (LO, HI)
C33 = (0.0, 0.0, 1.0)  # blue    at (HI, HI)
C30 = (1.0, 1.0, 0.0)  # yellow  at (HI, LO)


# ---------------------------------------------------------------------------
# Bit packing - MSH3: most-significant bit first, fields in the stated order
# ---------------------------------------------------------------------------


class BitWriter:
    """Pack fields MSB-first, with an explicit byte-align.

    The mirror of `mesh.rs`'s `BitReader`, written independently from the
    same clause rather than by transcribing the reader - a packer derived
    from the parser cannot falsify the parser.
    """

    def __init__(self) -> None:
        self.bits: list[int] = []

    def put(self, value: int, width: int) -> None:
        if value < 0 or value >= (1 << width):
            raise ValueError(f"{value} does not fit in {width} bits")
        for i in range(width - 1, -1, -1):
            self.bits.append((value >> i) & 1)

    def align(self) -> None:
        while len(self.bits) % 8:
            # Pad with 1s, not 0s. The clause says the pad bits "shall be
            # ignored"; padding with the value a lazy reader would find
            # least convenient is the cheap way to prove pdfcer ignores them.
            self.bits.append(1)

    def bytes(self) -> bytes:
        out = bytearray()
        bits = list(self.bits)
        while len(bits) % 8:
            bits.append(1)
        for i in range(0, len(bits), 8):
            b = 0
            for bit in bits[i : i + 8]:
                b = (b << 1) | bit
            out.append(b)
        return bytes(out)


def enc(value: float, lo: float, hi: float, width: int) -> int:
    """Inverse of MSH11's decode, so the fixture's numbers survive the round trip.

    `y = Dmin + x*(Dmax-Dmin)/(2^n - 1)`  =>  `x = (y-Dmin)*(2^n-1)/(Dmax-Dmin)`
    """
    span = hi - lo
    if span == 0:
        return 0
    x = round((value - lo) * ((1 << width) - 1) / span)
    return max(0, min((1 << width) - 1, x))


