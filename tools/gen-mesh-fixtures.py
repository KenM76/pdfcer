# Geometry
# ---------------------------------------------------------------------------


def straight_edge(a, b):
    """The two interior control points of a straight cubic from `a` to `b`."""
    return (
        (a[0] + (b[0] - a[0]) / 3.0, a[1] + (b[1] - a[1]) / 3.0),
        (a[0] + 2 * (b[0] - a[0]) / 3.0, a[1] + 2 * (b[1] - a[1]) / 3.0),
    )


def quad_boundary(p00, p03, p33, p30):
    """The 12 boundary control points of a straight-edged patch, in STREAM order.

    Stream order is the boundary walked counterclockwise from `p00`
    (`MSH29`): p00 p01 p02 p03 | p13 p23 p33 | p32 p31 p30 | p20 p10.

    Parameterised by the four CORNERS rather than by a rectangle, because a
    continued patch does not get to choose the orientation of its own `u=0`
    edge - it inherits it, and for edge flags 2 and 3 it inherits it
    REVERSED. A rectangle helper that always ran `p00` to `p03` upward could
    only author the flag-1 case, and authoring the other two with it
    produces a patch twisted into a bowtie. That is not a hypothetical: it
    is what the first draft of this generator emitted, and the picture
    looked enough like "a gradient" to need a second look.
    """
    p01, p02 = straight_edge(p00, p03)
    p13, p23 = straight_edge(p03, p33)
    p32, p31 = straight_edge(p33, p30)
    p20, p10 = straight_edge(p30, p00)
    return [p00, p01, p02, p03, p13, p23, p33, p32, p31, p30, p20, p10]


def square_boundary(x0, y0, x1, y1):
    """A rectangle, as `quad_boundary` corners: p00 lower-left, v upward."""
    return quad_boundary((x0, y0), (x0, y1), (x1, y1), (x1, y0))


def coons_internals(b):
    """The four internal points a Coons patch implies - MSH30, verbatim.

    Computed HERE, in the fixture generator, rather than read out of
    `mesh.rs`. That is what makes `type7_tensor.pdf` an independent check
    of the renderer's own copy of these equations: if the renderer's
    transcription is wrong, the two files stop agreeing.
    """
    (p00, p01, p02, p03, p13, p23, p33, p32, p31, p30, p20, p10) = b

    def f(a, bb, c, d, e, h, i, j):
        return tuple(
            (
                -4.0 * a[t]
                + 6.0 * (bb[t] + c[t])
                - 2.0 * (d[t] + e[t])
                + 3.0 * (h[t] + i[t])
                - j[t]
            )
            / 9.0
            for t in range(2)
        )

    p11 = f(p00, p01, p10, p03, p30, p31, p13, p33)
    p12 = f(p03, p02, p13, p00, p33, p32, p10, p30)
    p21 = f(p30, p31, p20, p33, p00, p01, p23, p03)
    p22 = f(p33, p32, p23, p30, p03, p02, p20, p00)
    # Stream order for the internals is the CYCLE p11 -> p12 -> p22 -> p21,
    # not row-major. MSH29's last four entries.
    return [p11, p12, p22, p21]


